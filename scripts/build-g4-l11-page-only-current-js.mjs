#!/usr/bin/env node

import {createHash} from "node:crypto";
import {
  lstat,
  mkdir,
  readFile,
  rename,
  writeFile,
} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

import {
  privateCurrentJsCalibrationMatches,
  upsertPrivateCurrentJsCalibration,
} from "./private-current-js-registry.mjs";
import {
  separatedCurrentJsCandidateStoragePath,
} from "./current-js-candidate-paths.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const GENERATOR_PATH = "scripts/build-g4-l11-page-only-current-js.mjs";
const ANIMATIONS_PATH = "catalog/animations.json";
const LESSONS_PATH = "catalog/lessons.json";
const PREDECESSOR_FREEZE_PATH =
  "catalog/product-bridge-calibrations/g4-l11-migration-factory-v1.json";
const CALIBRATION_ID = "g4-l11-page-only-current-js-43-v1";
const FREEZE_PATH =
  `catalog/product-bridge-calibrations/${CALIBRATION_ID}.json`;
const PRIVATE_REGISTRY_PATH = "packages/demos/private-current-js-registry.json";
const GENERATED_DATA_PATH =
  "apps/web/lib/g4-l11-page-only-current-js.generated.ts";
const RELEASE_ID = "lesson-g04-l11-coordinate-grid";
const ASSETLESS_PRODUCT_NATIVE_ID = "course-g04-l11-ts-002";

const ACCEPTANCE_EFFECTS = Object.freeze({
  authoritativeOriginalRuntime: false,
  naturalRuntimeReachabilityComplete: false,
  behaviorParityAccepted: false,
  visualFidelityAccepted: false,
  audioAccepted: false,
  humanVisualAccepted: false,
  humanAudioAccepted: false,
  ownerAccepted: false,
  strictComplete: false,
  releaseEligible: false,
  published: false,
});

function invariant(value, message) {
  if (!value) throw new Error(message);
}

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function jsonBytes(value) {
  return Buffer.from(`${JSON.stringify(value, null, 2)}\n`);
}

function projectPath(relativePath) {
  invariant(
    typeof relativePath === "string" && relativePath.length > 0 &&
      !path.isAbsolute(relativePath),
    `invalid project path: ${relativePath}`,
  );
  const absolute = path.resolve(ROOT, relativePath);
  invariant(absolute.startsWith(`${ROOT}${path.sep}`),
    `path escapes worktree: ${relativePath}`);
  return absolute;
}

async function bind(relativePath) {
  const absolute = projectPath(relativePath);
  const metadata = await lstat(absolute);
  invariant(metadata.isFile() && !metadata.isSymbolicLink(),
    `${relativePath}: expected an ordinary file`);
  const bytes = await readFile(absolute);
  return Object.freeze({
    path: relativePath,
    bytes: bytes.length,
    sha256: sha256(bytes),
  });
}

async function readJson(relativePath) {
  return JSON.parse((await readFile(projectPath(relativePath))).toString("utf8"));
}

async function synchronize(relativePath, bytes, check) {
  const target = projectPath(relativePath);
  if (check) {
    const current = await readFile(target).catch(() => null);
    invariant(current?.equals(bytes), `${relativePath}: generated output is stale`);
    return;
  }
  await mkdir(path.dirname(target), {recursive: true});
  const temporary = `${target}.tmp-${process.pid}`;
  await writeFile(temporary, bytes, {flag: "wx"});
  await rename(temporary, target);
}

async function frameTarget(animationId) {
  const timeline = await readFile(projectPath(
    `packages/demos/src/timelines/${animationId}.ts`,
  ), "utf8");
  const frameDomain = timeline.match(
    /"?(?:mainFrameDomain|sourceStaticFrameDomain)"?:\s*"(sprite-\d+)"/,
  )?.[1];
  const frameCount = Number(timeline.match(
    /"?(?:mainFrameCount|sourceStaticFrameCount)"?:\s*([0-9_]+)/,
  )?.[1]?.replaceAll("_", ""));
  const rootBeginFrame = Number(timeline.match(
    /"?rootBeginFrame"?:\s*([0-9_]+)/,
  )?.[1]?.replaceAll("_", ""));
  invariant(
    frameDomain && Number.isSafeInteger(frameCount) && frameCount > 1 &&
      Number.isSafeInteger(rootBeginFrame) && rootBeginFrame > 0,
    `${animationId}: maintained timeline frame target is invalid`,
  );
  return Object.freeze({
    frameDomain,
    frameCount,
    rootBeginFrame,
  });
}

function generatedDataSource(data) {
  return Buffer.from(
    `/* Generated by ${GENERATOR_PATH}. Do not edit. */\n` +
      `export const G4_L11_PAGE_ONLY_CURRENT_JS = Object.freeze(${JSON.stringify(data, null, 2)} as const);\n`,
  );
}

function sourceLabels(section) {
  return {
    en: {
      text: section.titleEnglish,
      sourceLanguage: "en",
      sourceStatus: "exact-course-xml",
      usesEnglishFallback: false,
    },
    es: {
      text: section.titleSpanish,
      sourceLanguage: "es",
      sourceStatus: "exact-course-xml",
      usesEnglishFallback: false,
    },
  };
}

async function build({check = false} = {}) {
  const [animations, lessons, predecessor, predecessorBinding,
    generatorBinding, registryBefore] = await Promise.all([
    readJson(ANIMATIONS_PATH),
    readJson(LESSONS_PATH),
    readJson(PREDECESSOR_FREEZE_PATH),
    bind(PREDECESSOR_FREEZE_PATH),
    bind(GENERATOR_PATH),
    readJson(PRIVATE_REGISTRY_PATH),
  ]);
  const lesson = lessons.lessons?.find((candidate) =>
    candidate.grade === 4 && candidate.lesson === 11);
  const members = animations.animations?.flatMap((animation) => {
    const references = animation.references?.courseXml?.filter((reference) =>
      reference.sourceXmlPath === lesson?.path &&
      Number.isSafeInteger(reference.occurrence) &&
      reference.occurrence > 0
    ) ?? [];
    return references.map((reference) => ({
      ordinal: reference.occurrence,
      animationId: animation.animationId,
      assetId: animation.assetId,
      xmlOccurrence: reference.occurrence,
      source: {
        path: animation.source?.path,
        sha256: animation.source?.sha256,
      },
    }));
  }).sort((left, right) => left.ordinal - right.ordinal);
  invariant(
    lesson?.sha256 ===
      "b5e0dddcf9e60124d54ecaf5d57d3254e2e0cea40cef1dd5a044a73c8ba4656a" &&
      members?.length === 43 &&
      members.every((member, index) => member.ordinal === index + 1) &&
      new Set(members.map(({animationId}) => animationId)).size === 43 &&
      lesson.pageReferenceCount === 43,
    "G4 L11 source-ordered 43-page catalog binding changed",
  );
  invariant(
    predecessor.calibrationId === "g4-l11-migration-factory-v1" &&
      predecessor.scope?.activeLessonPageCount === 43 &&
      predecessor.scope?.legacyCourseShellCount === 0 &&
      predecessor.selectedPages?.length === 1 &&
      registryBefore.schemaVersion === 2 &&
      Array.isArray(registryBefore.calibrations) &&
      registryBefore.calibrations.filter(({calibrationId}) =>
        calibrationId === CALIBRATION_ID).length <= 1 &&
      (registryBefore.calibrations.find(({calibrationId}) =>
        calibrationId === CALIBRATION_ID)?.entries?.length ?? 43) === 43,
    "G4 L11 one-page predecessor factory or registry changed",
  );

  const sectionOrdinals = new Map();
  const pages = [];
  for (const member of members) {
    const target = await frameTarget(member.animationId);
    const sectionCode = member.animationId.split("-")[3]?.toUpperCase();
    invariant(lesson.sections.some(({code}) => code === sectionCode),
      `${member.animationId}: section identity is invalid`);
    const sectionPageOrdinal = (sectionOrdinals.get(sectionCode) ?? 0) + 1;
    sectionOrdinals.set(sectionCode, sectionPageOrdinal);
    const moduleBinding = await bind(
      `packages/demos/src/modules/${member.animationId}.tsx`,
    );
    const timelineBinding = await bind(
      `packages/demos/src/timelines/${member.animationId}.ts`,
    );
    let asset = null;
    if (member.animationId !== ASSETLESS_PRODUCT_NATIVE_ID) {
      const base = `public/flash-assets/courses/${member.animationId}`;
      asset = Object.freeze({
        manifest: await bind(separatedCurrentJsCandidateStoragePath(
          `${base}/manifest.json`,
        )),
        runtime: await bind(separatedCurrentJsCandidateStoragePath(
          `${base}/canvas-renderer.js`,
        )),
      });
    }
    pages.push(Object.freeze({
      ordinal: member.ordinal,
      animationId: member.animationId,
      assetId: member.assetId,
      sectionCode,
      sectionPageOrdinal,
      sourceOccurrence: member.xmlOccurrence,
      sourceSwfSha256: member.source.sha256,
      ...target,
      complexityLane: member.animationId === "course-g04-l11-in-010"
        ? "interactive-understood"
        : "behavior-heavy",
      implementationKind: member.animationId === ASSETLESS_PRODUCT_NATIVE_ID
        ? "product-native-current-js"
        : asset.manifest.path.includes("page-only-private-current-js")
          ? "manual-source-static-current-js"
          : "preserved-current-js-candidate",
      module: moduleBinding,
      timeline: timelineBinding,
      asset,
    }));
  }
  invariant(
    lesson.sections.every(({code, pageReferenceCount}) =>
      sectionOrdinals.get(code) === pageReferenceCount),
    "G4 L11 section denominators changed",
  );

  const selectedPages = pages.map((page) => ({
    animationId: page.animationId,
    globalPageOrdinal: page.ordinal,
    sectionCode: page.sectionCode,
    sectionPageOrdinal: page.sectionPageOrdinal,
    complexityLane: page.complexityLane,
    selectionStatus: page.implementationKind,
    source: {swfSha256: page.sourceSwfSha256},
    module: page.module,
    timeline: page.timeline,
    runtime: {
      frameDomain: page.frameDomain,
      frameCount: page.frameCount,
      rootBeginFrame: page.rootBeginFrame,
      playbackMode: "once",
      asset: page.asset,
      naturalRuntimeEstablished: false,
    },
  }));
  const freeze = {
    schemaVersion: 1,
    calibrationId: CALIBRATION_ID,
    status: "page-only-private-current-js-registered-43-of-43",
    predecessor: {
      ...predecessorBinding,
      preservedConclusions: [
        "The v1 factory remains a dated one-page calibration and its NO_GO scale-out decision is not rewritten.",
        "This successor registers acceptance-neutral page runtimes without promoting fidelity, audio, behavior, human, Owner, strict, release, or publication gates.",
      ],
    },
    scope: {
      releaseId: RELEASE_ID,
      activePageCount: 43,
      courseShellCount: 0,
      selectedPageCount: 43,
      productNativePageCount: pages.filter(({implementationKind}) =>
        implementationKind === "product-native-current-js").length,
      canvasAssetPageCount: pages.filter(({asset}) => asset).length,
    },
    inputs: {
      generator: generatorBinding,
      lessonCatalog: await bind(LESSONS_PATH),
      animationCatalog: await bind(ANIMATIONS_PATH),
    },
    selectedPages,
    modernMyLesson: {
      pageOnlyDescriptor: true,
      exactSourceOrderMemberCount: 43,
      legacyCourseShellIncluded: false,
      privateRouteOnly: true,
    },
    acceptanceEffects: ACCEPTANCE_EFFECTS,
    strictAcceptanceEffect: "none",
  };
  const freezeBytes = jsonBytes(freeze);
  await synchronize(FREEZE_PATH, freezeBytes, check);
  const freezeSha256 = sha256(freezeBytes);

  const privateCalibration = {
    calibrationId: CALIBRATION_ID,
    freezeManifest: FREEZE_PATH,
    entries: pages.map((page) => ({
      key: page.animationId,
      module: `./modules/${page.animationId}`,
      maturity: "private-current-js",
      complexityLane: page.complexityLane,
    })),
  };
  if (check) {
    invariant(
      privateCurrentJsCalibrationMatches(registryBefore, privateCalibration),
      `${PRIVATE_REGISTRY_PATH}: ${CALIBRATION_ID} is stale or absent`,
    );
  } else {
    await synchronize(
      PRIVATE_REGISTRY_PATH,
      jsonBytes(upsertPrivateCurrentJsCalibration(
        registryBefore,
        privateCalibration,
      )),
      false,
    );
  }

  const data = {
    schemaVersion: 1,
    calibrationId: CALIBRATION_ID,
    releaseId: RELEASE_ID,
    course: {
      grade: 4,
      lesson: 11,
      title: lesson.titleDisplay,
      sourceXmlPath: lesson.path,
      sourceXmlSha256: lesson.sha256,
      activePageCount: 43,
      courseShellCount: 0,
    },
    freeze: {path: FREEZE_PATH, sha256: freezeSha256},
    sections: lesson.sections.map((section) => ({
      order: section.number,
      code: section.code,
      activePageCount: section.pageReferenceCount,
      firstActiveAnimationId: pages.find(({sectionCode}) =>
        sectionCode === section.code).animationId,
      labels: sourceLabels(section),
    })),
    pages: pages.map((page) => ({
      ordinal: page.ordinal,
      animationId: page.animationId,
      assetId: page.assetId,
      sectionCode: page.sectionCode,
      sectionPageOrdinal: page.sectionPageOrdinal,
      sourceOccurrence: page.sourceOccurrence,
      frameDomain: page.frameDomain,
      frameCount: page.frameCount,
      complexityLane: page.complexityLane,
      implementationKind: page.implementationKind,
      registered: true,
    })),
    acceptanceEffects: ACCEPTANCE_EFFECTS,
  };
  await synchronize(GENERATED_DATA_PATH, generatedDataSource(data), check);
  return {
    calibrationId: CALIBRATION_ID,
    activePages: 43,
    registered: 43,
    courseShellCount: 0,
    productNativePages: pages.filter(({implementationKind}) =>
      implementationKind === "product-native-current-js").length,
    canvasAssetPages: pages.filter(({asset}) => asset).length,
    freezePath: FREEZE_PATH,
    freezeSha256,
    check,
  };
}

const check = process.argv.slice(2).includes("--check");
const unexpected = process.argv.slice(2).filter((argument) => argument !== "--check");
invariant(unexpected.length === 0, `unknown arguments: ${unexpected.join(" ")}`);
build({check}).then((result) => {
  process.stdout.write(`${JSON.stringify(result, null, 2)}\n`);
}).catch((error) => {
  process.stderr.write(`${error.stack ?? error.message}\n`);
  process.exitCode = 1;
});
