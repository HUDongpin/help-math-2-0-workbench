#!/usr/bin/env node

import {createHash} from 'node:crypto';
import {copyFile, mkdir, readFile, stat, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const scriptPath = fileURLToPath(import.meta.url);
const workspaceRoot = path.resolve(path.dirname(scriptPath), '..');
const irPath = path.join(workspaceRoot, 'tools/g4-l5-ffdec-canvas-pcode-product-factory/product-ir.json');
const catalogPath = path.join(workspaceRoot, 'catalog/animations.json');
const freezeRelative = 'catalog/product-bridge-calibrations/g4-l5-ffdec-product-factory-v2.json';
const generatedConfigRelative = 'packages/demos/src/g4-l5-product-candidates.generated.ts';
const generatedPrivateLoaderRelative = 'packages/demos/src/g4-l5-product-registry.generated.ts';
const privateRegistryRelative = 'packages/demos/private-current-js-registry.json';
const selectedOccurrences = Object.freeze([2, 11, 30, 37, 43, 52]);
const acceptanceEffects = Object.freeze({
  authoritativeOriginalRuntime: false,
  fidelityAccepted: false,
  audioAccepted: false,
  humanVisualAccepted: false,
  ownerAccepted: false,
  strictComplete: false,
  released: false,
  published: false,
});

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function stableJson(value) {
  return `${JSON.stringify(value, null, 2)}\n`;
}

function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

async function exactFile(relativePath, expectedSha256) {
  const filePath = path.join(workspaceRoot, relativePath);
  const fileStat = await stat(filePath);
  invariant(fileStat.isFile(), `${relativePath} is not a regular file`);
  const bytes = await readFile(filePath);
  invariant(sha256(bytes) === expectedSha256, `${relativePath} no longer matches ${expectedSha256}`);
  return bytes;
}

function courseSequence(catalog) {
  const pages = [];
  for (const animation of catalog.animations ?? []) {
    if (animation?.classification?.grade !== 4 || animation?.classification?.lesson !== 5 || animation?.flags?.shell) continue;
    for (const reference of animation?.references?.courseXml ?? []) {
      if (reference.sourceXmlPath !== 'HELP_COURSES/ELMGR4/L5/index.xml' || !Number.isSafeInteger(reference.occurrence)) continue;
      pages.push({
        animationId: animation.animationId,
        assetId: animation.assetId,
        sourceOccurrence: reference.occurrence,
        sourcePath: animation.source.path,
        swfSha256: animation.source.sha256,
        sectionCode: animation.classification.section?.code,
        titleEnglish: animation.classification.titleEnglish ?? animation.classification.titleDisplay,
        titleSpanish: animation.classification.titleSpanish,
      });
    }
  }
  return pages.sort((left, right) => left.sourceOccurrence - right.sourceOccurrence);
}

function generatedConfigSource(ir) {
  return [
    '// Generated by scripts/build-g4-l5-product-factory.mjs. Do not edit.',
    '',
    `export const G4_L5_PRODUCT_FACTORY_CALIBRATION_ID = ${JSON.stringify(ir.calibrationId)} as const;`,
    '',
    `export const G4_L5_PRODUCT_CANDIDATES = ${JSON.stringify(ir.members, null, 2)} as const;`,
    '',
    'export type G4L5ProductCandidateConfig =',
    '  (typeof G4_L5_PRODUCT_CANDIDATES)[number];',
    '',
    'export function findG4L5ProductCandidate(animationId: string):',
    '  G4L5ProductCandidateConfig | undefined {',
    '  return G4_L5_PRODUCT_CANDIDATES.find(',
    '    (candidate) => candidate.animationId === animationId,',
    '  );',
    '}',
    '',
  ].join('\n');
}

function moduleSource(animationId) {
  return [
    '// Generated by scripts/build-g4-l5-product-factory.mjs. Do not edit.',
    "import {findG4L5ProductCandidate} from '../g4-l5-product-candidates.generated';",
    "import {createG4L5ProductCandidateModule} from '../g4-l5-product-candidate';",
    '',
    `const config = findG4L5ProductCandidate(${JSON.stringify(animationId)});`,
    `if (!config) throw new Error(${JSON.stringify(`Missing generated config for ${animationId}`)});`,
    '',
    'export default createG4L5ProductCandidateModule(config);',
    '',
  ].join('\n');
}

function privateLoaderSource(ir) {
  const loaders = ir.members.map((member) =>
    `  '${member.animationId}': () => import('./modules/${member.animationId}').then(({default: animationModule}) => animationModule)`
  );
  return [
    '// Generated by scripts/build-g4-l5-product-factory.mjs. Do not edit.',
    "import type {AnimationModule} from './contract';",
    '',
    'const loaders: Readonly<Record<string, () => Promise<AnimationModule>>> = Object.freeze({',
    loaders.join(',\n'),
    '});',
    '',
    'export const g4L5ProductModuleKeys = Object.freeze(Object.keys(loaders));',
    '',
    'export async function loadG4L5ProductModule(',
    '  key: string,',
    '): Promise<AnimationModule | undefined> {',
    '  return loaders[key]?.();',
    '}',
    '',
  ].join('\n');
}

function privateRegistry(ir) {
  return {
    schemaVersion: 1,
    registryScope: 'private-engineering',
    calibrationId: ir.calibrationId,
    freezeManifestPath: freezeRelative,
    entries: ir.members.map((member) => ({
      key: member.animationId,
      module: `./modules/${member.animationId}`,
      maturity: 'private-current-js',
      calibrationId: ir.calibrationId,
    })),
  };
}

async function expectedOutputs(ir) {
  const outputs = new Map();
  outputs.set(generatedConfigRelative, generatedConfigSource(ir));
  outputs.set(generatedPrivateLoaderRelative, privateLoaderSource(ir));
  for (const member of ir.members) {
    outputs.set(`packages/demos/src/modules/${member.animationId}.tsx`, moduleSource(member.animationId));
  }
  outputs.set(privateRegistryRelative, stableJson(privateRegistry(ir)));
  return outputs;
}

async function writeOrCheckText(relativePath, source, check) {
  const destination = path.join(workspaceRoot, relativePath);
  if (check) {
    const current = await readFile(destination, 'utf8').catch(() => '');
    invariant(current === source, `${relativePath} is stale or absent`);
    return;
  }
  await mkdir(path.dirname(destination), {recursive: true});
  await writeFile(destination, source);
}

async function materializeAudio(ir, check) {
  const receipts = [];
  for (const member of ir.members) {
    if (!member.audio) continue;
    const sourceRelative = `source-assets/flash/HELP MATH_ORIGINAL FILES/${member.audio.sourcePath}`;
    const sourceBytes = await exactFile(sourceRelative, member.audio.sha256);
    invariant(sourceBytes.byteLength === member.audio.bytes, `${member.animationId} audio byte count drifted`);
    const destinationRelative = `apps/web/public/flash-assets/courses/${member.animationId}/audio/source-narration-undetermined.mp3`;
    const destination = path.join(workspaceRoot, destinationRelative);
    if (check) {
      await exactFile(destinationRelative, member.audio.sha256);
    } else {
      await mkdir(path.dirname(destination), {recursive: true});
      const current = await readFile(destination).catch(() => null);
      if (current) {
        invariant(sha256(current) === member.audio.sha256, `${destinationRelative} exists with different bytes`);
      } else {
        await copyFile(path.join(workspaceRoot, sourceRelative), destination);
      }
    }
    receipts.push({
      animationId: member.animationId,
      sourcePath: sourceRelative,
      destinationPath: destinationRelative,
      bytes: member.audio.bytes,
      durationMs: member.audio.durationMs,
      sha256: member.audio.sha256,
      spokenLanguage: 'undetermined',
      acceptanceEffect: 'none',
    });
  }
  return receipts;
}

async function buildState() {
  const [irBytes, catalogBytes, scriptBytes] = await Promise.all([
    readFile(irPath),
    readFile(catalogPath),
    readFile(scriptPath),
  ]);
  const ir = JSON.parse(irBytes);
  const catalog = JSON.parse(catalogBytes);
  invariant(ir.schemaVersion === 1, 'product IR must use schemaVersion 1');
  invariant(ir.grade === 4 && ir.lesson === 5, 'product IR must bind G4 L5');
  invariant(ir.members?.length === 6, 'product IR must contain six members');
  invariant(JSON.stringify(ir.acceptanceEffects) === JSON.stringify(acceptanceEffects), 'product IR acceptance effects must remain all false');
  invariant(ir.members.map((member) => member.sourceOccurrence).join(',') === selectedOccurrences.join(','), 'product IR source occurrences drifted');
  const sequence = courseSequence(catalog);
  invariant(sequence.length === 53, 'G4 L5 source sequence must remain 53 pages');
  invariant(sequence.map((page) => page.sourceOccurrence).join(',') === Array.from({length: 53}, (_, index) => index + 1).join(','), 'G4 L5 source occurrences must remain contiguous 1..53');
  const outputs = await expectedOutputs(ir);
  for (const member of ir.members) {
    const page = sequence[member.sourceOccurrence - 1];
    invariant(
      page?.animationId === member.animationId &&
        page.assetId === member.source.assetId &&
        page.swfSha256 === member.source.swfSha256 &&
        page.sourcePath === member.source.swfPath,
      `${member.animationId} no longer matches catalog source occurrence`,
    );
    await exactFile(`source-assets/flash/HELP MATH_ORIGINAL FILES/${member.source.swfPath}`, member.source.swfSha256);
    if (member.source.flaPath) {
      await exactFile(`source-assets/flash/HELP MATH_ORIGINAL FILES/${member.source.flaPath}`, member.source.flaSha256);
    }
  }
  const runManifestBytes = await exactFile(ir.compilerEvidence.runManifestPath, ir.compilerEvidence.runManifestSha256);
  return {
    ir,
    sequence,
    outputs,
    hashes: {
      irSha256: sha256(irBytes),
      catalogSha256: sha256(catalogBytes),
      generatorSha256: sha256(scriptBytes),
      compilerRunManifestSha256: sha256(runManifestBytes),
    },
  };
}

async function buildFreeze(state, audioReceipts) {
  const generatedOutputs = [...state.outputs].map(([relativePath, source]) => ({
    path: relativePath,
    sha256: sha256(Buffer.from(source)),
  }));
  return {
    schemaVersion: 1,
    calibrationId: state.ir.calibrationId,
    status: 'private-current-js-engineering-candidate',
    grade: 4,
    lesson: 5,
    lessonTitle: 'Multiplication',
    pageOnlyScope: {
      activePageCount: 53,
      legacyCourseShellCount: 0,
      selectedCurrentJsCount: 6,
      remainingCurrentJsCount: 47,
    },
    sourceBindings: state.hashes,
    sourceSequenceAuthority: 'course-xml-occurrence',
    selectedOccurrences,
    sourceSequence: state.sequence,
    members: state.ir.members,
    generatedOutputs,
    audioMaterialization: audioReceipts,
    licensingBoundary: {
      compilerEvidence: 'private-evidence-only-not-bundled',
      productImplementation: 'independently-maintained-react-svg-css',
    },
    acceptanceEffects,
  };
}

export async function runProductFactory({check = false} = {}) {
  const state = await buildState();
  const audioReceipts = await materializeAudio(state.ir, check);
  for (const [relativePath, source] of state.outputs) {
    await writeOrCheckText(relativePath, source, check);
  }
  const freeze = await buildFreeze(state, audioReceipts);
  await writeOrCheckText(freezeRelative, stableJson(freeze), check);
  return freeze;
}

async function main() {
  const check = process.argv.includes('--check');
  const write = process.argv.includes('--write');
  invariant(check !== write, 'Choose exactly one of --write or --check');
  const freeze = await runProductFactory({check});
  process.stdout.write(`${check ? 'checked' : 'wrote'} ${freeze.pageOnlyScope.selectedCurrentJsCount} G4 L5 product candidates\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  main().catch((error) => {
    process.stderr.write(`${error.stack ?? error.message}\n`);
    process.exitCode = 1;
  });
}
