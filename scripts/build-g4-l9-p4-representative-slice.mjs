async function loadPreflight() {
  const bytes = await readFile(preflightPath);
  const document = JSON.parse(bytes.toString('utf8'));
  if (document.decision?.result !== 'NO_GO_SCALE_OUT') {
    throw new Error('P3 decision drifted from NO_GO_SCALE_OUT');
  }
  const selectedPages = document.occurrences.filter((page) =>
    SELECTED_OCCURRENCES.includes(page.sourceOccurrence)
  );
  if (
    selectedPages.length !== 14 ||
    selectedPages.map((page) => page.sourceOccurrence).join(',') !==
      SELECTED_OCCURRENCES.join(',')
  ) {
    throw new Error('The frozen 14-page source-order selection drifted');
  }
  return {bytes, document, selectedPages};
}

export async function buildGeneratedArtifacts() {
  const preflight = await loadPreflight();
  const configs = preflight.selectedPages
    .filter((page) => page.animationId !== GS002_ID)
    .map(pageConfig);
  const freeze = stableJson(freezeDocument(preflight, preflight.selectedPages));
  const artifacts = new Map([
    [FREEZE_PATH, freeze],
    [GENERATED_WEB_PATH, generatedWebSource(preflight, sha256(freeze))],
    ...gsEvidence(),
  ]);
  for (const config of configs) {
    artifacts.set(
      `packages/demos/src/timelines/${config.animationId}.ts`,
      timelineSource(config),
    );
    if (FACTORY_IDS.has(config.animationId)) {
      artifacts.set(
        `packages/demos/src/modules/${config.animationId}.tsx`,
        factoryModuleSource(config),
      );
    }
    artifacts.set(
      `apps/web/candidate-assets/flash-assets/2026-08-22-page-only-candidates-v1/courses/${config.animationId}/canvas-renderer.js`,
      canvasSource(config),
    );
    for (const [relative, content] of workspaceArtifacts(config)) {
      artifacts.set(relative, content);
    }
  }
  return {artifacts, configs, preflight};
}

async function sourceRootArgument() {
  const index = process.argv.indexOf('--source-root');
  return index >= 0 ? process.argv[index + 1] : null;
}

async function materialize({artifacts, configs}, mode) {
  const mismatches = [];
  for (const [relative, content] of artifacts) {
    const target = path.join(repositoryRoot, relative);
    const expected = Buffer.isBuffer(content) ? content : Buffer.from(content);
    if (mode === 'write') {
      await mkdir(path.dirname(target), {recursive: true});
      await writeFile(target, expected);
    } else {
      const actual = await readFile(target).catch(() => null);
      if (!actual || !actual.equals(expected)) mismatches.push(relative);
    }
  }

  const sourceRoot = await sourceRootArgument();
  for (const config of configs.filter((item) => item.audio)) {
    const relative =
      `apps/web/candidate-assets/flash-assets/2026-08-22-page-only-candidates-v1/courses/${config.animationId}/audio/source-narration-undetermined.mp3`;
    const target = path.join(repositoryRoot, relative);
    if (mode === 'write') {
      if (!sourceRoot) throw new Error('--source-root is required when writing exact audio');
      const source = path.join(sourceRoot, config.audio.sourcePath);
      const bytes = await readFile(source);
      if (bytes.length !== config.audio.sourceBytes || sha256(bytes) !== config.audio.sourceSha256) {
        throw new Error(`${config.animationId} exact source audio identity drifted`);
      }
      await mkdir(path.dirname(target), {recursive: true});
      await writeFile(target, bytes);
    } else {
      const actual = await readFile(target).catch(() => null);
      if (
        !actual ||
        actual.length !== config.audio.sourceBytes ||
        sha256(actual) !== config.audio.sourceSha256
      ) {
        mismatches.push(relative);
      }
    }
  }
  if (mismatches.length) {
    throw new Error(`Generated P4 artifacts are stale:\n${mismatches.sort().join('\n')}`);
  }
}

async function main() {
  const built = await buildGeneratedArtifacts();
  const mode = process.argv.includes('--write') ? 'write' : 'check';
  await materialize(built, mode);
  process.stdout.write(
    `G4 L9 P4 ${mode} PASS: ${built.artifacts.size} text artifacts + 10 exact audio assets\n`,
  );
}

if (process.argv[1] && path.resolve(process.argv[1]) === scriptPath) {
  main().catch((error) => {
    process.stderr.write(`${error.stack ?? error.message}\n`);
    process.exitCode = 1;
  });
}
