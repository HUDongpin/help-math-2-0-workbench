import {createHash} from 'node:crypto';
import {mkdir, readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const id = 'course-g04-l03-in-004';
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
const report = JSON.parse(await readFile(path.join(root, 'reports/g4-l3-embedded-audio-archive.json'), 'utf8'));
const page = report.items.find((item) => item.animationId === id);
const source = page.source.swf;
if (sha256(await readFile(path.join(root, source.path))) !== source.expectedSha256) {
  throw new Error('IN004 preserved source hash mismatch');
}
const roles = {'sprite-55': 'correct', 'sprite-155': 'wrong', 'sprite-159': 'complete'};
const assets = [];
for (const [domain, role] of Object.entries(roles)) {
  const stream = page.embeddedAudio.soundStreams.find((item) => item.ownerDomainId === domain);
  const bytes = await readFile(path.join(root, stream.payload.archivePath));
  if (sha256(bytes) !== stream.payload.sha256) throw new Error(`${domain} archive hash mismatch`);
  const relative = `courses/${id}/audio/feedback-${role}.mp3`;
  const target = path.join(root, 'public/flash-assets', relative);
  await mkdir(path.dirname(target), {recursive: true});
  try {
    await writeFile(target, bytes, {flag: 'wx'});
  } catch (error) {
    if (error.code !== 'EEXIST' || sha256(await readFile(target)) !== stream.payload.sha256) throw error;
  }
  assets.push({id: `in004-feedback-${role}`, language: 'en', activation: 'interaction-feedback', spokenLanguage: 'undetermined', source: `/flash-assets/${relative}?sha256=${stream.payload.sha256}`, sha256: stream.payload.sha256});
}
const generated = `// Generated by scripts/materialize-g4-l3-in004-feedback-audio.mjs.\n// Exact SWF stream payloads; English page routing, spoken-language review pending.\nimport type {InteractiveAudioAsset} from './contract';\n\nexport const IN004_FEEDBACK_AUDIO: readonly InteractiveAudioAsset[] = Object.freeze(${JSON.stringify(assets, null, 2)}.map((asset) => Object.freeze({...asset, language: 'en' as const, activation: 'interaction-feedback' as const, spokenLanguage: 'undetermined' as const})));\n`;
await writeFile(path.join(root, 'packages/demos/src/g4-l3-in004-feedback-audio.generated.ts'), generated);
console.log(`Materialized ${assets.length} exact IN004 feedback streams; no acceptance or deployment claimed.`);
