function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function sha256Text(value) {
  return createHash("sha256").update(value).digest("hex");
}

function validateContainerDriveId(value) {
  if (typeof value !== "string" || value !== value.trim() || !DRIVE_ID_PATTERN.test(value)) {
    throw new Error("Container Drive ID is missing or invalid");
  }
  return value;
}

function validateCanonicalPrefix(value = DEFAULT_CANONICAL_PREFIX) {
  const normalized = normalizeRelativePath(value, "canonical prefix");
  if (!ALLOWED_CANONICAL_PREFIXES.has(normalized)) {
    throw new Error(
      `Unsupported canonical prefix: ${normalized}. Allowed prefixes: ${[
        ...ALLOWED_CANONICAL_PREFIXES,
      ].join(", ")}`,
    );
  }
  return normalized;
}

function normalizeRelativePath(value, label = "relative path") {
  if (typeof value !== "string") throw new Error(`${label} must be a string`);
  if (value === "" || value !== value.trim()) {
    throw new Error(`${label} is empty or has outer whitespace`);
  }
  if (value !== value.normalize("NFC")) throw new Error(`${label} is not Unicode NFC-normalized`);
  if (value.startsWith("/") || value.includes("\\") || CONTROL_CHARACTER_PATTERN.test(value)) {
    throw new Error(`${label} is absolute, contains a backslash, or contains a control character`);
  }
  const segments = value.split("/");
  if (
    segments.some(
      (segment) =>
        segment === "" ||
        segment === "." ||
        segment === ".." ||
        segment !== segment.trim(),
    )
  ) {
    throw new Error(`${label} contains an empty, traversal, dot, or whitespace-ambiguous segment`);
  }
  return segments.join("/");
}

function extensionForPath(relativePath) {
  const extension = path.posix.extname(relativePath).toLowerCase();
  return extension.startsWith(".") ? extension.slice(1) : extension;
}

function sourceTypeForExtension(extension) {
  return SOURCE_TYPE_BY_EXTENSION.get(extension) ?? "other-technical";
}

function parseNonNegativeSafeInteger(value, label) {
  if (!Number.isSafeInteger(value) || value < 0) {
    throw new Error(`${label} must be a non-negative safe integer`);
  }
  return value;
}

function validateSha256(value, label) {
  const normalized = String(value ?? "").toLowerCase();
  if (!SHA256_PATTERN.test(normalized)) throw new Error(`${label} is not a valid SHA-256`);
  return normalized;
}

function calculateChecksumSetSha256(files) {
  const hash = createHash("sha256");
  for (const file of files) {
    hash.update(`${JSON.stringify([file.manifestRelativePath, file.bytes, file.sha256])}\n`);
  }
  return hash.digest("hex");
}

function parseZipHashManifest(content) {
  let parsed;
  try {
    parsed = JSON.parse(content);
  } catch (error) {
    throw new Error(`Invalid ZIP hash manifest JSON: ${error.message}`);
  }
  if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
    throw new Error("ZIP hash manifest must be a JSON object");
  }
  if (parsed.schemaVersion !== 1 || parsed.algorithm !== "sha256" || !Array.isArray(parsed.files)) {
    throw new Error(
      'ZIP hash manifest must use schemaVersion 1, algorithm "sha256", and a files array',
    );
  }
  if (typeof parsed.sourceDirectory !== "string" || parsed.sourceDirectory.trim() === "") {
    throw new Error("ZIP hash manifest must declare sourceDirectory");
  }

  const records = parsed.files.map((file, index) => {
    const rowNumber = index + 1;
    if (!file || typeof file !== "object" || Array.isArray(file)) {
      throw new Error(`ZIP hash manifest row ${rowNumber} must be an object`);
    }
    const manifestRelativePath = normalizeRelativePath(
      file.path,
      `ZIP hash manifest row ${rowNumber} path`,
    );
    const foldedManifestPath = manifestRelativePath.toLocaleLowerCase("en-US");
    const embeddedCanonicalRoot = [...ALLOWED_CANONICAL_PREFIXES].some(
      (canonicalPrefix) => {
        const foldedPrefix = canonicalPrefix.toLocaleLowerCase("en-US");
        return (
          foldedManifestPath === foldedPrefix ||
          foldedManifestPath.startsWith(`${foldedPrefix}/`) ||
          foldedManifestPath.includes(`/${foldedPrefix}/`)
        );
      },
    );
    if (embeddedCanonicalRoot) {
      throw new Error(
        `ZIP hash manifest row ${rowNumber} embeds a supported canonical root; paths must be relative to the selected ZIP container root`,
      );
    }
    const bytes = parseNonNegativeSafeInteger(
      file.bytes,
      `ZIP hash manifest row ${rowNumber} bytes`,
    );
    const sha256 = validateSha256(file.sha256, `ZIP hash manifest row ${rowNumber} SHA-256`);
    const extension = extensionForPath(manifestRelativePath);
    return {
      manifestRelativePath,
      bytes,
      sha256,
      extension,
      sourceType: sourceTypeForExtension(extension),
      isTechnical: TECHNICAL_EXTENSIONS.has(extension),
    };
  });

  const originalPaths = records.map((record) => record.manifestRelativePath);
  const sortedPaths = [...originalPaths].sort(compareText);
  if (originalPaths.some((value, index) => value !== sortedPaths[index])) {
    throw new Error("ZIP hash manifest files are not in deterministic path order");
  }

  const byFoldedPath = new Map();
  for (const record of records) {
    const folded = record.manifestRelativePath.toLocaleLowerCase("en-US");
    const prior = byFoldedPath.get(folded);
    if (prior) {
      throw new Error(
        `ZIP hash manifest has a duplicate or case-colliding path: ${prior} and ${record.manifestRelativePath}`,
      );
    }
    byFoldedPath.set(folded, record.manifestRelativePath);
  }

  const declaredFileCount = parseNonNegativeSafeInteger(
    parsed.fileCount,
    "ZIP hash manifest fileCount",
  );
  if (declaredFileCount !== records.length) {
    throw new Error("ZIP hash manifest fileCount does not match files.length");
  }
  const totalBytes = records.reduce((total, record) => total + record.bytes, 0);
  if (!Number.isSafeInteger(totalBytes)) throw new Error("ZIP hash manifest total bytes overflow");
  const declaredTotalBytes = parseNonNegativeSafeInteger(
    parsed.totalBytes,
    "ZIP hash manifest totalBytes",
  );
  if (declaredTotalBytes !== totalBytes) {
    throw new Error("ZIP hash manifest totalBytes does not match the file records");
  }
  const declaredChecksumSetSha256 = validateSha256(
    parsed.checksumSetSha256,
    "ZIP hash manifest checksumSetSha256",
  );
  const calculatedChecksumSetSha256 = calculateChecksumSetSha256(records);
  if (declaredChecksumSetSha256 !== calculatedChecksumSetSha256) {
    throw new Error("ZIP hash manifest checksumSetSha256 does not match the file records");
  }

  return {
    sourceDirectory: parsed.sourceDirectory,
    generatedAt: typeof parsed.generatedAt === "string" ? parsed.generatedAt : null,
    fileCount: records.length,
    totalBytes,
    checksumSetSha256: calculatedChecksumSetSha256,
    records,
  };
}

function parseCanonicalCatalog(content) {
  let parsed;
  try {
    parsed = JSON.parse(content);
  } catch (error) {
    throw new Error(`Invalid canonical source catalog JSON: ${error.message}`);
  }
  if (!parsed || !Array.isArray(parsed.files)) {
    throw new Error('Canonical source catalog must contain a "files" array');
  }

  const records = parsed.files.map((file, index) => {
    const rowNumber = index + 1;
    if (!file || typeof file !== "object" || Array.isArray(file)) {
      throw new Error(`Canonical source catalog row ${rowNumber} must be an object`);
    }
    const canonicalPath = normalizeRelativePath(
      file.path,
      `Canonical source catalog row ${rowNumber} path`,
    );
    return {
      canonicalPath,
      bytes: parseNonNegativeSafeInteger(
        file.bytes,
        `Canonical source catalog row ${rowNumber} bytes`,
      ),
      sha256: validateSha256(
        file.sha256,
        `Canonical source catalog row ${rowNumber} SHA-256`,
      ),
      extension: extensionForPath(canonicalPath),
    };
  });

  const byPath = new Map();
  const byFoldedPath = new Map();
  const bySha256 = new Map();
  for (const record of records) {
    if (byPath.has(record.canonicalPath)) {
      throw new Error(`Canonical source catalog repeats ${record.canonicalPath}`);
    }
    const folded = record.canonicalPath.toLocaleLowerCase("en-US");
    const caseVariant = byFoldedPath.get(folded);
    if (caseVariant) {
      throw new Error(
        `Canonical source catalog has a case-colliding path: ${caseVariant.canonicalPath} and ${record.canonicalPath}`,
      );
    }
    byPath.set(record.canonicalPath, record);
    byFoldedPath.set(folded, record);
    const hashMatches = bySha256.get(record.sha256) ?? [];
    hashMatches.push(record);
    bySha256.set(record.sha256, hashMatches);
  }
  for (const matches of bySha256.values()) {
    matches.sort((left, right) => compareText(left.canonicalPath, right.canonicalPath));
  }
  return { records, byPath, byFoldedPath, bySha256 };
}

function createCounter() {
  const values = new Map();
  return {
    add(key) {
      values.set(key, (values.get(key) ?? 0) + 1);
    },
    object() {
      return Object.fromEntries([...values].sort(([left], [right]) => compareText(left, right)));
    },
  };
}

function classifyRecord(record, catalog, historicalBySha256) {
  const exact = catalog.byPath.get(record.canonicalPath) ?? null;
  const foldedPath = record.canonicalPath.toLocaleLowerCase("en-US");
  const caseVariant = exact ? null : catalog.byFoldedPath.get(foldedPath) ?? null;
  const canonicalHashMatches = catalog.bySha256.get(record.sha256) ?? [];
  const historicalMatches = historicalBySha256.get(record.sha256) ?? [];

  let pathStatus = exact
    ? "canonical-exact-path-present"
    : caseVariant
      ? "canonical-path-case-variant"
      : "canonical-exact-path-missing";
  let byteIdentityStatus = "hash-not-in-local-evidence";
  let byteDuplicateStatus = "none";
  let conflictStatus = "none";
  let intakeDecision = "candidate";
  let disposition = "candidate-new-source-in-quarantine";
  const reasons = [];

  if (exact) {
    if (record.sha256 === exact.sha256) {
      byteIdentityStatus = "canonical-exact-path-byte-identical";
      byteDuplicateStatus = "same-canonical-path";
      intakeDecision = "skip";
      disposition = "skip-byte-identical-canonical";
      reasons.push("The exact canonical path has the same SHA-256.");
    } else {
      byteIdentityStatus = canonicalHashMatches.length
        ? "canonical-byte-duplicate-at-other-path"
        : historicalMatches.length
          ? "historical-byte-duplicate"
          : "hash-not-in-local-evidence";
      byteDuplicateStatus = canonicalHashMatches.length
        ? "different-canonical-path"
        : historicalMatches.length
          ? "historical-evidence"
          : "none";
      conflictStatus = "canonical-exact-path-content-conflict";
      intakeDecision = "hold";
      disposition = "hold-exact-path-content-conflict";
      reasons.push("The exact canonical path exists with a different SHA-256.");
    }
  } else if (caseVariant) {
    byteIdentityStatus = canonicalHashMatches.length
      ? "canonical-byte-duplicate-at-other-path"
      : historicalMatches.length
        ? "historical-byte-duplicate"
        : "hash-not-in-local-evidence";
    byteDuplicateStatus = canonicalHashMatches.length
      ? "different-canonical-path"
      : historicalMatches.length
        ? "historical-evidence"
        : "none";
    conflictStatus = "canonical-path-case-conflict";
    intakeDecision = "hold";
    disposition = "hold-path-case-conflict";
    reasons.push("A canonical path differs only by case; placement identity must be resolved.");
  } else if (canonicalHashMatches.length) {
    byteIdentityStatus = "canonical-byte-duplicate-at-other-path";
    byteDuplicateStatus = "different-canonical-path";
    intakeDecision = "hold";
    disposition = "hold-placement-alias-review";
    reasons.push(
      "The SHA-256 already exists at another canonical placement; byte identity does not collapse placement identity.",
    );
  } else if (historicalMatches.length) {
    byteIdentityStatus = "historical-byte-duplicate";
    byteDuplicateStatus = "historical-evidence";
    intakeDecision = "hold";
    disposition = "hold-historical-custody-review";
    reasons.push(
      "The SHA-256 exists in the optional historical evidence root; custody and placement still require review.",
    );
  } else {
    reasons.push("The exact canonical path is missing and the SHA-256 is absent from local evidence.");
  }

  return {
    containerDriveId: null,
    canonicalPrefix: null,
    driveEntryId: null,
    driveEntryIdStatus: "unavailable-in-folder-zip-export",
    manifestRelativePath: record.manifestRelativePath,
    canonicalPath: record.canonicalPath,
    extension: record.extension,
    sourceType: record.sourceType,
    bytes: record.bytes,
    sha256: record.sha256,
    pathStatus,
    byteIdentityStatus,
    byteDuplicateStatus,
    isByteDuplicate: byteDuplicateStatus !== "none",
    conflictStatus,
    intakeDecision,
    disposition,
    canonicalExact: exact
      ? { path: exact.canonicalPath, bytes: exact.bytes, sha256: exact.sha256 }
      : null,
    canonicalCaseVariantPath: caseVariant?.canonicalPath ?? null,
    canonicalHashMatchPaths: canonicalHashMatches.map((match) => match.canonicalPath),
    historicalHashMatchRefs: historicalMatches,
    reasons,
  };
}

function reconcileZipManifest(
  manifest,
  catalog,
  {
    containerDriveId,
    canonicalPrefix = DEFAULT_CANONICAL_PREFIX,
    historicalBySha256 = new Map(),
    manifestSha256 = null,
    catalogSha256 = null,
    historicalScan = null,
  } = {},
) {
  const validatedContainerDriveId = validateContainerDriveId(containerDriveId);
  const validatedCanonicalPrefix = validateCanonicalPrefix(canonicalPrefix);
  const expectedSourceDirectory = path.posix.basename(validatedCanonicalPrefix);
  if (manifest.sourceDirectory !== expectedSourceDirectory) {
    throw new Error(
      `ZIP hash manifest sourceDirectory ${manifest.sourceDirectory} does not match canonical prefix root ${expectedSourceDirectory}`,
    );
  }
  const pathCounts = createCounter();
  const identityCounts = createCounter();
  const duplicateCounts = createCounter();
  const conflictCounts = createCounter();
  const decisionCounts = createCounter();
  const dispositionCounts = createCounter();
  const sourceTypeCounts = createCounter();
  const records = [];
  let excludedNonTechnicalRows = 0;

  for (const input of manifest.records) {
    if (!input.isTechnical) {
      excludedNonTechnicalRows += 1;
      continue;
    }
    const mappedInput = {
      ...input,
      canonicalPath: `${validatedCanonicalPrefix}/${input.manifestRelativePath}`,
    };
    const record = classifyRecord(mappedInput, catalog, historicalBySha256);
    record.containerDriveId = validatedContainerDriveId;
    record.canonicalPrefix = validatedCanonicalPrefix;
    records.push(record);
    pathCounts.add(record.pathStatus);
    identityCounts.add(record.byteIdentityStatus);
    duplicateCounts.add(record.byteDuplicateStatus);
    conflictCounts.add(record.conflictStatus);
    decisionCounts.add(record.intakeDecision);
    dispositionCounts.add(record.disposition);
    sourceTypeCounts.add(record.sourceType);
  }
  records.sort((left, right) => compareText(left.canonicalPath, right.canonicalPath));

  return {
    schemaVersion: 1,
    artifactType: "help-math-drive-zip-source-intake-plan",
    mode: "hash-manifest-plan-only-no-source-mutation",
    evidenceBoundary:
      "Container provenance plus path, byte count, and SHA-256 support intake triage only; folder ZIP exports do not prove per-entry Drive identity, Flash fidelity, acceptance, strict completion, or release readiness.",
    driveProvenance: {
      containerDriveId: validatedContainerDriveId,
      canonicalPrefix: validatedCanonicalPrefix,
      entryDriveIds: "unavailable-in-folder-zip-export",
      syntheticEntryDriveIds: "prohibited",
    },
    inputs: {
      manifestSha256,
      canonicalCatalogSha256: catalogSha256,
      manifestChecksumSetSha256: manifest.checksumSetSha256,
      manifestSourceDirectory: manifest.sourceDirectory,
      manifestGeneratedAt: manifest.generatedAt,
      historicalScan,
    },
    policy: {
      manifestPathsRelativeTo: expectedSourceDirectory,
      canonicalPrefix: validatedCanonicalPrefix,
      technicalExtensions: [...TECHNICAL_EXTENSIONS].sort(compareText),
      nonTechnicalRows: "counted-but-not-emitted",
      historicalPaths: "opaque-reference-only",
      automaticSourcePromotion: "prohibited",
    },
    counts: {
      manifestRows: manifest.fileCount,
      manifestTotalBytes: manifest.totalBytes,
      selectedTechnicalRows: records.length,
      excludedNonTechnicalRows,
      bySourceType: sourceTypeCounts.object(),
      byPathStatus: pathCounts.object(),
      byByteIdentityStatus: identityCounts.object(),
      byByteDuplicateStatus: duplicateCounts.object(),
      byConflictStatus: conflictCounts.object(),
      byIntakeDecision: decisionCounts.object(),
      byDisposition: dispositionCounts.object(),
    },
    records,
  };
}

async function sha256FileStable(filePath) {
  const before = await stat(filePath);
  const digest = await new Promise((resolve, reject) => {
    const hash = createHash("sha256");
    const input = createReadStream(filePath);
    input.on("error", reject);
    input.on("data", (chunk) => hash.update(chunk));
    input.on("end", () => resolve(hash.digest("hex")));
  });
  const after = await stat(filePath);
  if (
    before.size !== after.size ||
    before.ino !== after.ino ||
    before.mtimeMs !== after.mtimeMs ||
    before.ctimeMs !== after.ctimeMs
  ) {
    throw new Error(`Historical source changed while being hashed: ${filePath}`);
  }
  return digest;
}

async function listHistoricalTechnicalFiles(
  root,
  directory = root,
  result = [],
  summary = { skippedSymlinkCount: 0 },
) {
  const entries = await readdir(directory, { withFileTypes: true });
  entries.sort((left, right) => compareText(left.name, right.name));
  for (const entry of entries) {
    const entryPath = path.join(directory, entry.name);
    if (entry.isSymbolicLink()) {
      summary.skippedSymlinkCount += 1;
    } else if (entry.isDirectory()) {
      await listHistoricalTechnicalFiles(root, entryPath, result, summary);
    } else if (entry.isFile() && TECHNICAL_EXTENSIONS.has(extensionForPath(entry.name))) {
      result.push(entryPath);
    }
  }
  return { files: result, summary };
}

async function mapConcurrent(values, limit, mapper) {
  const results = new Array(values.length);
  let nextIndex = 0;
  async function worker() {
    while (nextIndex < values.length) {
      const index = nextIndex;
      nextIndex += 1;
      results[index] = await mapper(values[index], index);
    }
  }
  await Promise.all(
    Array.from({ length: Math.min(limit, Math.max(values.length, 1)) }, () => worker()),
  );
  return results;
}

async function scanHistoricalRoot(root, manifestRecords) {
  const resolvedRoot = path.resolve(root);
  const rootInfo = await lstat(resolvedRoot);
  if (rootInfo.isSymbolicLink() || !rootInfo.isDirectory()) {
    throw new Error("Historical root must be a real read-only directory, not a symlink or file");
  }
  const requiredSizes = new Set(
    manifestRecords.filter((record) => record.isTechnical).map((record) => record.bytes),
  );
  const { files, summary } = await listHistoricalTechnicalFiles(resolvedRoot);
  const candidates = [];
  for (const filePath of files) {
    const info = await stat(filePath);
    if (requiredSizes.has(info.size)) candidates.push(filePath);
  }
  const rootSalt = sha256Text(resolvedRoot);
  const hashed = await mapConcurrent(candidates, 6, async (filePath) => {
    const relativePath = path.relative(resolvedRoot, filePath).split(path.sep).join("/");
    return {
      sha256: await sha256FileStable(filePath),
      ref: `historical-${sha256Text(`${rootSalt}\0${relativePath}`).slice(0, 20)}`,
    };
  });
  const bySha256 = new Map();
  for (const record of hashed) {
    const refs = bySha256.get(record.sha256) ?? [];
    refs.push(record.ref);
    bySha256.set(record.sha256, refs);
  }
  for (const refs of bySha256.values()) refs.sort(compareText);
  return {
    bySha256,
    summary: {
      rootRef: `historical-root-${rootSalt.slice(0, 20)}`,
      technicalFileCount: files.length,
      hashCandidateFileCount: candidates.length,
      skippedSymlinkCount: summary.skippedSymlinkCount,
    },
  };
}

function csvCell(value) {
  const string = value === null || value === undefined ? "" : String(value);
  if (!/[",\r\n]/.test(string)) return string;
  return `"${string.replace(/"/g, '""')}"`;
}

