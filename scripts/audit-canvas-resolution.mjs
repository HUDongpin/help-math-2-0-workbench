export function reportBytes(document) {
  invariant(
    document?.reportType === 'canvas-resolution-static-audit'
      && SHA256_PATTERN.test(document.payloadSha256 || ''),
    'invalid Canvas resolution audit document',
  );
  const recomputed = sha256(Buffer.from(canonicalJson(document.payload)));
  invariant(
    document.payloadSha256 === recomputed,
    `audit payload hash mismatch: declared ${document.payloadSha256}, `
      + `recomputed ${recomputed}`,
  );
  return jsonBytes(document);
}

export async function writeOrCheckReport({
  document,
  outputPath,
  check = false,
  projectRoot = DEFAULT_PROJECT_ROOT,
}) {
  invariant(
    typeof outputPath === 'string' && outputPath.length > 0,
    '--output <path> is required for write/check report operations',
  );
  const absoluteOutputPath = path.isAbsolute(outputPath)
    ? path.resolve(outputPath)
    : path.resolve(projectRoot, outputPath);
  const expectedBytes = reportBytes(document);
  if (check) {
    const observed = await readFile(absoluteOutputPath).catch((error) => {
      if (error?.code === 'ENOENT') {
        throw new Error(`audit output is missing: ${absoluteOutputPath}`);
      }
      throw error;
    });
    invariant(
      observed.equals(expectedBytes),
      `${absoluteOutputPath}: Canvas resolution audit output is stale`,
    );
    return {
      operation: 'check',
      outputPath: absoluteOutputPath,
      bytes: observed.length,
      sha256: sha256(observed),
      payloadSha256: document.payloadSha256,
    };
  }
  const existingMetadata = await lstat(absoluteOutputPath).catch((error) => {
    if (error?.code === 'ENOENT') return null;
    throw error;
  });
  if (existingMetadata !== null) {
    invariant(
      existingMetadata.isFile() && !existingMetadata.isSymbolicLink(),
      `${absoluteOutputPath}: existing audit output must be an ordinary file`,
    );
    const observed = await readFile(absoluteOutputPath);
    invariant(
      observed.equals(expectedBytes),
      `${absoluteOutputPath}: refusing to overwrite immutable audit evidence`,
    );
    return {
      operation: 'existing-identical',
      outputPath: absoluteOutputPath,
      bytes: observed.length,
      sha256: sha256(observed),
      payloadSha256: document.payloadSha256,
    };
  }
  await mkdir(path.dirname(absoluteOutputPath), {recursive: true});
  const temporaryPath =
    `${absoluteOutputPath}.tmp-${process.pid}-${document.payloadSha256.slice(0, 12)}`;
  await unlink(temporaryPath).catch((error) => {
    if (error?.code !== 'ENOENT') throw error;
  });
  try {
    await writeFile(temporaryPath, expectedBytes, {flag: 'wx'});
    const staged = await readFile(temporaryPath);
    invariant(staged.equals(expectedBytes), 'staged audit evidence changed');
    await link(temporaryPath, absoluteOutputPath);
    await unlink(temporaryPath);
  } catch (error) {
    await unlink(temporaryPath).catch(() => {});
    throw error;
  }
  return {
    operation: 'write',
    outputPath: absoluteOutputPath,
    bytes: expectedBytes.length,
    sha256: sha256(expectedBytes),
    payloadSha256: document.payloadSha256,
  };
}

export function usage() {
  return [
    'Usage: node scripts/audit-canvas-resolution.mjs [options]',
    '',
    'Options:',
    `  --profile <path>  Immutable asset profile (default: ${DEFAULT_PROFILE_PATH})`,
    '  --scope <name>    pilot | production-five (default: production-five)',
    '  --output <path>   Write deterministic hash-bound JSON to this path',
    '  --check           Recompute and byte-compare --output; never write',
    '  --help            Show this help',
  ].join('\n');
}

export function parseArguments(argv) {
  const options = {
    profilePath: DEFAULT_PROFILE_PATH,
    scope: 'production-five',
    outputPath: null,
    check: false,
    help: false,
  };
  const valueFor = (argument, index, name) => {
    const prefix = `${name}=`;
    if (argument.startsWith(prefix)) {
      const value = argument.slice(prefix.length);
      invariant(value.length > 0, `${name} requires a value`);
      return {value, consumed: 0};
    }
    invariant(argument === name, `unknown argument: ${argument}`);
    invariant(index + 1 < argv.length, `${name} requires a value`);
    invariant(!argv[index + 1].startsWith('--'), `${name} requires a value`);
    return {value: argv[index + 1], consumed: 1};
  };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--help') options.help = true;
    else if (argument === '--check') options.check = true;
    else if (argument === '--profile' || argument.startsWith('--profile=')) {
      const parsed = valueFor(argument, index, '--profile');
      options.profilePath = parsed.value;
      index += parsed.consumed;
    } else if (argument === '--scope' || argument.startsWith('--scope=')) {
      const parsed = valueFor(argument, index, '--scope');
      options.scope = parsed.value;
      index += parsed.consumed;
    } else if (argument === '--output' || argument.startsWith('--output=')) {
      const parsed = valueFor(argument, index, '--output');
      options.outputPath = parsed.value;
      index += parsed.consumed;
    } else throw new Error(`unknown argument: ${argument}`);
  }
  invariant(
    ['pilot', 'production-five'].includes(options.scope),
    `invalid --scope ${options.scope}; expected pilot or production-five`,
  );
  if (options.check) {
    invariant(
      options.outputPath,
      '--check requires --output <path> so regenerated bytes can be compared',
    );
  }
  return options;
}

async function main() {
  const options = parseArguments(process.argv.slice(2));
  if (options.help) {
    process.stdout.write(`${usage()}\n`);
    return;
  }
  const document = await auditCanvasResolution({
    profilePath: options.profilePath,
    scope: options.scope,
  });
  if (options.outputPath) {
    const result = await writeOrCheckReport({
      document,
      outputPath: options.outputPath,
      check: options.check,
    });
    process.stdout.write(`${JSON.stringify({
      ...result,
      outputPath: normalizedProjectPath(
        DEFAULT_PROJECT_ROOT,
        result.outputPath,
      ),
    })}\n`);
  } else process.stdout.write(reportBytes(document));
}

if (process.argv[1] && path.resolve(process.argv[1]) === SCRIPT_PATH) {
  main().catch((error) => {
    process.stderr.write(`audit-canvas-resolution: ${error.message}\n`);
    process.exitCode = 1;
  });
}
