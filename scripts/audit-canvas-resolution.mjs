function deepFreeze(value) {
  if (value && typeof value === 'object' && !Object.isFrozen(value)) {
    Object.freeze(value);
    for (const child of Object.values(value)) deepFreeze(child);
  }
  return value;
}

function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function canonicalValue(value) {
  if (Array.isArray(value)) return value.map(canonicalValue);
  if (value && typeof value === 'object') {
    const result = {};
    for (const key of Object.keys(value).sort(compareText)) {
      result[key] = canonicalValue(value[key]);
    }
    return result;
  }
  return value;
}

export function canonicalJson(value) {
  return JSON.stringify(canonicalValue(value));
}

function jsonBytes(value) {
  return Buffer.from(`${JSON.stringify(value, null, 2)}\n`);
}

export function computeProfileChecksumSet(entries) {
  const rows = entries.map((entry, index) => {
    invariant(
      Number.isSafeInteger(entry?.bytes) && entry.bytes >= 0,
      `profile entry ${index}: bytes must be a non-negative safe integer`,
    );
    invariant(
      SHA256_PATTERN.test(entry?.sha256 || ''),
      `profile entry ${index}: sha256 must be a lowercase SHA-256 digest`,
    );
    invariant(
      typeof entry?.relativePath === 'string' && entry.relativePath.length > 0,
      `profile entry ${index}: relativePath is required`,
    );
    return `${entry.sha256} ${entry.bytes} ${entry.relativePath}`;
  });
  rows.sort((left, right) => {
    const leftPath = left.slice(left.indexOf(' ', left.indexOf(' ') + 1) + 1);
    const rightPath = right.slice(
      right.indexOf(' ', right.indexOf(' ') + 1) + 1,
    );
    return compareText(leftPath, rightPath);
  });
  return sha256(Buffer.from(rows.join('\n')));
}

function normalizedProjectPath(projectRoot, absolutePath) {
  const relative = path.relative(projectRoot, absolutePath);
  if (
    relative.length > 0
    && relative !== '..'
    && !relative.startsWith(`..${path.sep}`)
    && !path.isAbsolute(relative)
  ) {
    return relative.split(path.sep).join('/');
  }
  if (relative === '') return '.';
  return absolutePath;
}

function resolveWithin(projectRoot, relativePath, label) {
  invariant(
    typeof relativePath === 'string'
      && relativePath.length > 0
      && !path.isAbsolute(relativePath)
      && !relativePath.includes('\\'),
    `${label}: expected a non-empty POSIX project-relative path`,
  );
  const normalized = path.posix.normalize(relativePath);
  invariant(
    normalized === relativePath
      && normalized !== '..'
      && !normalized.startsWith('../'),
    `${label}: path escapes or is not normalized: ${relativePath}`,
  );
  const resolved = path.resolve(projectRoot, ...relativePath.split('/'));
  const prefix = `${path.resolve(projectRoot)}${path.sep}`;
  invariant(resolved.startsWith(prefix), `${label}: path escapes project root`);
  return resolved;
}

async function readOrdinaryFile(absolutePath, label) {
  const metadata = await lstat(absolutePath).catch((error) => {
    if (error?.code === 'ENOENT') return null;
    throw error;
  });
  invariant(metadata !== null, `${label}: file is missing`);
  invariant(
    metadata.isFile() && !metadata.isSymbolicLink(),
    `${label}: expected an ordinary non-symlink file`,
  );
  return readFile(absolutePath);
}

function validateContract(contract) {
  invariant(
    contract && typeof contract === 'object',
    'resolution audit contract is required',
  );
  invariant(
    typeof contract.contractId === 'string' && contract.contractId.length > 0,
    'contractId is required',
  );
  invariant(
    Array.isArray(contract.lessons) && contract.lessons.length > 0,
    'contract.lessons must be non-empty',
  );
  invariant(
    Array.isArray(contract.pilotRendererIds)
      && contract.pilotRendererIds.length > 0,
    'contract.pilotRendererIds must be non-empty',
  );
  invariant(
    (Array.isArray(contract.placementCatalogs)
      && contract.placementCatalogs.length > 0)
      || (Array.isArray(contract.placements)
        && contract.placements.length > 0),
    'contract must provide placementCatalogs or inline placements',
  );
  if (Array.isArray(contract.placementCatalogs)) {
    for (const [index, catalog] of contract.placementCatalogs.entries()) {
      invariant(
        typeof catalog?.path === 'string'
          && catalog.path.length > 0
          && SHA256_PATTERN.test(catalog.sha256 || ''),
        `invalid placement catalog contract at index ${index}`,
      );
    }
  }
  invariant(
    contract.profile?.sha256 === null
      || SHA256_PATTERN.test(contract.profile?.sha256 || ''),
    'contract.profile.sha256 must be null or an exact lowercase SHA-256',
  );
  invariant(
    Number.isInteger(contract.nativeCanvas?.width)
      && contract.nativeCanvas.width > 0
      && Number.isInteger(contract.nativeCanvas?.height)
      && contract.nativeCanvas.height > 0
      && Array.isArray(contract.nativeCanvas?.rootTransform)
      && contract.nativeCanvas.rootTransform.length === 6
      && contract.nativeCanvas.rootTransform.every(Number.isFinite),
    'contract.nativeCanvas must declare positive dimensions and a six-value transform',
  );
  const releaseIds = new Set();
  let placementCount = 0;
  let uniqueRendererCount = 0;
  for (const lesson of contract.lessons) {
    invariant(
      typeof lesson.lessonId === 'string'
        && typeof lesson.releaseId === 'string'
        && Number.isInteger(lesson.placementCount)
        && lesson.placementCount > 0
        && Number.isInteger(lesson.uniqueRendererCount)
        && lesson.uniqueRendererCount > 0
        && lesson.placementCount >= lesson.uniqueRendererCount
        && Array.isArray(lesson.repeatedPlacements),
      `invalid lesson contract: ${lesson?.lessonId || '<unknown>'}`,
    );
    invariant(
      !releaseIds.has(lesson.releaseId),
      `duplicate contract releaseId: ${lesson.releaseId}`,
    );
    releaseIds.add(lesson.releaseId);
    const repeatedExtra = lesson.repeatedPlacements.reduce(
      (total, repeated) => {
        invariant(
          typeof repeated.animationId === 'string'
            && repeated.animationId.length > 0
            && Number.isInteger(repeated.occurrenceCount)
            && repeated.occurrenceCount >= 2,
          `${lesson.lessonId}: invalid repeated placement`,
        );
        if (repeated.placementOrdinals !== undefined) {
          invariant(
            Array.isArray(repeated.placementOrdinals)
              && repeated.placementOrdinals.length
                === repeated.occurrenceCount
              && repeated.placementOrdinals.every(
                (ordinal) => Number.isInteger(ordinal) && ordinal > 0,
              ),
            `${lesson.lessonId}: invalid repeated placement ordinals`,
          );
        }
        if (repeated.placementIds !== undefined) {
          invariant(
            Array.isArray(repeated.placementIds)
              && repeated.placementIds.length === repeated.occurrenceCount
              && repeated.placementIds.every(
                (placementId) =>
                  typeof placementId === 'string' && placementId.length > 0,
              ),
            `${lesson.lessonId}: invalid repeated placement IDs`,
          );
        }
        return total + repeated.occurrenceCount - 1;
      },
      0,
    );
    invariant(
      lesson.placementCount - lesson.uniqueRendererCount === repeatedExtra,
      `${lesson.lessonId}: placement/unique/repetition denominator mismatch`,
    );
    placementCount += lesson.placementCount;
    uniqueRendererCount += lesson.uniqueRendererCount;
  }
  invariant(
    new Set(contract.pilotRendererIds).size
      === contract.pilotRendererIds.length,
    'contract.pilotRendererIds contains duplicates',
  );
  return {releaseIds, placementCount, uniqueRendererCount};
}

function validatePlacementRows({placements, contract, rendererEntries}) {
  const contractState = validateContract(contract);
  invariant(
    placements.length === contractState.placementCount,
    `placement evidence denominator mismatch: expected `
      + `${contractState.placementCount}, observed ${placements.length}`,
  );
  const placementIds = new Set();
  const rendererById = new Map(
    rendererEntries.map((entry) => [entry.animationId, entry]),
  );
  for (const lesson of contract.lessons) {
    const rows = placements
      .filter(({releaseId}) => releaseId === lesson.releaseId)
      .sort((left, right) => left.ordinal - right.ordinal);
    invariant(
      rows.length === lesson.placementCount,
      `${lesson.lessonId}: placement evidence count mismatch`,
    );
    invariant(
      new Set(rows.map(({animationId}) => animationId)).size
        === lesson.uniqueRendererCount,
      `${lesson.lessonId}: placement evidence renderer denominator mismatch`,
    );
    for (const [index, row] of rows.entries()) {
      invariant(
        row.lessonId === lesson.lessonId
          && row.ordinal === index + 1
          && typeof row.placementId === 'string'
          && row.placementId.length > 0
          && !placementIds.has(row.placementId),
        `${lesson.lessonId}: invalid placement identity at ordinal ${index + 1}`,
      );
      placementIds.add(row.placementId);
      const renderer = rendererById.get(row.animationId);
      invariant(
        renderer?.releaseId === lesson.releaseId,
        `${row.placementId}: renderer is absent or release-bound incorrectly`,
      );
      invariant(
        typeof row.sourcePath === 'string'
          && row.sourcePath.length > 0
          && SHA256_PATTERN.test(row.sourceSha256 || ''),
        `${row.placementId}: exact source path and SHA-256 are required`,
      );
    }
  }
  return Object.freeze([...placements].sort((left, right) =>
    compareText(left.placementId, right.placementId)));
}

async function loadPlacementEvidence({projectRoot, contract, rendererEntries}) {
  if (Array.isArray(contract.placements)) {
    return {
      inputs: [{kind: 'inline-contract', placementCount: contract.placements.length}],
      placements: validatePlacementRows({
        placements: contract.placements,
        contract,
        rendererEntries,
      }),
    };
  }
  const inputReceipts = [];
  const releaseDocuments = new Map();
  for (const catalog of contract.placementCatalogs) {
    const absolutePath = resolveWithin(projectRoot, catalog.path, catalog.path);
    const bytes = await readOrdinaryFile(absolutePath, catalog.path);
    invariant(
      sha256(bytes) === catalog.sha256,
      `${catalog.path}: placement catalog SHA-256 differs from the contract`,
    );
    let document;
    try {
      document = JSON.parse(bytes.toString('utf8'));
    } catch (error) {
      throw new Error(`${catalog.path}: invalid placement catalog JSON: ${error.message}`);
    }
    invariant(
      Array.isArray(document?.releases),
      `${catalog.path}: releases must be an array`,
    );
    inputReceipts.push({
      kind: 'hash-bound-release-catalog',
      path: catalog.path,
      bytes: bytes.length,
      sha256: sha256(bytes),
    });
    for (const release of document.releases) {
      if (!contract.lessons.some(({releaseId}) => releaseId === release.releaseId)) {
        continue;
      }
      invariant(
        !releaseDocuments.has(release.releaseId),
        `duplicate placement release evidence: ${release.releaseId}`,
      );
      releaseDocuments.set(release.releaseId, release);
    }
  }
  const placements = [];
  for (const lesson of contract.lessons) {
    const release = releaseDocuments.get(lesson.releaseId);
    invariant(release, `missing placement release evidence: ${lesson.releaseId}`);
    const activePageMembers = Array.isArray(release.members)
      ? release.members.filter(
        ({releaseRole}) => releaseRole === 'active-xml-referenced-page',
      )
      : [];
    invariant(
      release.grade === lesson.grade
        && release.lesson === lesson.lesson
        && release.expectedCounts?.activeXmlReferencedPages
          === lesson.placementCount
        && Array.isArray(release.members)
        && activePageMembers.length === lesson.placementCount
        && new Set(activePageMembers.map(({animationId}) => animationId)).size
          === lesson.uniqueRendererCount,
      `${lesson.releaseId}: release placement counts differ from the contract`,
    );
    for (const member of activePageMembers) {
      const derivedPlacementId =
        `${lesson.lessonId}-placement-${String(member.ordinal).padStart(3, '0')}`;
      placements.push({
        lessonId: lesson.lessonId,
        releaseId: lesson.releaseId,
        ordinal: member.ordinal,
        placementId: member.placementId || derivedPlacementId,
        placementIdEvidence: member.placementId
          ? 'release-member-exact'
          : 'derived-from-release-lesson-and-ordinal',
        animationId: member.animationId,
        xmlOccurrence: member.xmlOccurrence,
        sourcePath: member.source?.path,
        sourceSha256: member.source?.sha256,
      });
    }
  }
  return {
    inputs: inputReceipts,
    placements: validatePlacementRows({placements, contract, rendererEntries}),
  };
}

function validateProfileEntry(entry, index) {
  const label = `profile entry ${index}`;
  invariant(entry && typeof entry === 'object', `${label}: object required`);
  invariant(
    typeof entry.assetPath === 'string'
      && entry.assetPath.startsWith('courses/')
      && !entry.assetPath.includes('\\')
      && path.posix.normalize(entry.assetPath) === entry.assetPath,
    `${label}: invalid assetPath`,
  );
  invariant(
    entry.relativePath === entry.assetPath.slice('courses/'.length),
    `${label}: relativePath does not match assetPath`,
  );
  invariant(
    ['public', 'server-audio'].includes(entry.storageRoot),
    `${label}: unsupported storageRoot ${entry.storageRoot}`,
  );
  invariant(
    typeof entry.releaseId === 'string' && entry.releaseId.length > 0,
    `${label}: releaseId is required`,
  );
  invariant(
    Number.isSafeInteger(entry.bytes) && entry.bytes >= 0,
    `${label}: invalid bytes`,
  );
  invariant(
    SHA256_PATTERN.test(entry.sha256 || ''),
    `${label}: invalid sha256`,
  );
}

function rendererIdentity(entry) {
  const match = /^courses\/([^/]+)\/canvas-renderer\.js$/u.exec(
    entry.assetPath,
  );
  invariant(
    entry.storageRoot !== 'public' || match,
    `${entry.assetPath}: renderer path is not canonical`,
  );
  return match?.[1] || null;
}

async function loadAndValidateProfile({
  projectRoot,
  profilePath,
  contract,
}) {
  const absoluteProfilePath = path.isAbsolute(profilePath)
    ? path.resolve(profilePath)
    : path.resolve(projectRoot, profilePath);
  const profileMetadata = await lstat(absoluteProfilePath).catch((error) => {
    if (error?.code === 'ENOENT') {
      throw new Error(
        `Canvas resolution profile is missing: ${absoluteProfilePath}. `
          + `Pass --profile <path> to an immutable Current-JS asset profile.`,
      );
    }
    throw error;
  });
  invariant(
    profileMetadata.isFile() && !profileMetadata.isSymbolicLink(),
    `Canvas resolution profile must be an ordinary non-symlink file: `
      + absoluteProfilePath,
  );
  const profileBytes = await readFile(absoluteProfilePath);
  if (contract.profile?.sha256) {
    invariant(
      sha256(profileBytes) === contract.profile.sha256,
      `profile file SHA-256 is outside the audit contract: expected `
        + `${contract.profile.sha256}, observed ${sha256(profileBytes)}`,
    );
  }
  let profile;
  try {
    profile = JSON.parse(profileBytes.toString('utf8'));
  } catch (error) {
    throw new Error(
      `Canvas resolution profile is not valid JSON: ${absoluteProfilePath}: `
        + error.message,
    );
  }
  invariant(
    Number.isInteger(profile?.schemaVersion) && profile.schemaVersion >= 1,
    'profile.schemaVersion must be a positive integer',
  );
  invariant(
    typeof profile.profileId === 'string' && profile.profileId.length > 0,
    'profile.profileId is required',
  );
  invariant(Array.isArray(profile.entries), 'profile.entries must be an array');
  profile.entries.forEach(validateProfileEntry);

  const entryKeys = new Set();
  for (const entry of profile.entries) {
    const key = `${entry.storageRoot}\u0000${entry.relativePath}`;
    invariant(!entryKeys.has(key), `duplicate profile entry: ${entry.assetPath}`);
    entryKeys.add(key);
  }

  const publicCount = profile.entries.filter(
    ({storageRoot}) => storageRoot === 'public',
  ).length;
  const serverAudioCount = profile.entries.filter(
    ({storageRoot}) => storageRoot === 'server-audio',
  ).length;
  invariant(
    profile.counts?.public === publicCount
      && profile.counts?.serverAudio === serverAudioCount
      && profile.counts?.total === profile.entries.length,
    'profile.counts does not match profile.entries',
  );
  const checksumSetSha256 = computeProfileChecksumSet(profile.entries);
  invariant(
    profile.checksumSetSha256 === checksumSetSha256,
    `profile checksum set mismatch: declared ${profile.checksumSetSha256}, `
      + `recomputed ${checksumSetSha256}`,
  );

  if (contract.profile?.profileId) {
    invariant(
      profile.profileId === contract.profile.profileId,
      `profileId mismatch: expected ${contract.profile.profileId}, `
        + `observed ${profile.profileId}`,
    );
  }
  if (contract.profile?.checksumSetSha256) {
    invariant(
      checksumSetSha256 === contract.profile.checksumSetSha256,
      `profile checksum is outside the audit contract: expected `
        + `${contract.profile.checksumSetSha256}, observed ${checksumSetSha256}`,
    );
  }
  if (contract.profile?.counts) {
    invariant(
      publicCount === contract.profile.counts.public
        && serverAudioCount === contract.profile.counts.serverAudio
        && profile.entries.length === contract.profile.counts.total,
      'profile entry counts are outside the audit contract',
    );
  }

  const contractReleaseIds = contract.lessons.map(({releaseId}) => releaseId);
  invariant(
    Array.isArray(profile.approvedReleaseIds)
      && JSON.stringify(profile.approvedReleaseIds)
        === JSON.stringify(contractReleaseIds),
    'profile.approvedReleaseIds does not exactly match the ordered five-lesson contract',
  );

  const rendererEntries = profile.entries
    .filter(
      (entry) =>
        entry.storageRoot === 'public'
        && entry.assetPath.endsWith('/canvas-renderer.js'),
    )
    .map((entry) => ({...entry, animationId: rendererIdentity(entry)}))
    .sort((left, right) => compareText(left.animationId, right.animationId));
  const rendererIds = new Set();
  for (const entry of rendererEntries) {
    invariant(
      !rendererIds.has(entry.animationId),
      `duplicate renderer animationId: ${entry.animationId}`,
    );
    rendererIds.add(entry.animationId);
  }

  const contractState = validateContract(contract);
  invariant(
    rendererEntries.length === contractState.uniqueRendererCount,
    `renderer denominator mismatch: expected ${contractState.uniqueRendererCount}, `
      + `observed ${rendererEntries.length}`,
  );
  for (const lesson of contract.lessons) {
    const count = rendererEntries.filter(
      ({releaseId}) => releaseId === lesson.releaseId,
    ).length;
    invariant(
      count === lesson.uniqueRendererCount,
      `${lesson.lessonId}: expected ${lesson.uniqueRendererCount} renderers, `
        + `observed ${count}`,
    );
    for (const repeated of lesson.repeatedPlacements) {
      invariant(
        rendererEntries.some(
          ({animationId, releaseId}) =>
            animationId === repeated.animationId
            && releaseId === lesson.releaseId,
        ),
        `${lesson.lessonId}: repeated renderer is absent: ${repeated.animationId}`,
      );
    }
  }
  invariant(
    rendererEntries.every(({releaseId}) =>
      contractState.releaseIds.has(releaseId)
    ),
    'profile contains a renderer outside the production-five release contract',
  );
  const missingPilotIds = contract.pilotRendererIds.filter(
    (animationId) => !rendererIds.has(animationId),
  );
  invariant(
    missingPilotIds.length === 0,
    `profile is missing pilot renderers: ${missingPilotIds.join(', ')}`,
  );

  return {
    absoluteProfilePath,
    displayProfilePath: normalizedProjectPath(
      projectRoot,
      absoluteProfilePath,
    ),
    profileBytes,
    profile,
    rendererEntries,
    rendererIds,
    checksumSetSha256,
    publicCount,
    serverAudioCount,
  };
}

