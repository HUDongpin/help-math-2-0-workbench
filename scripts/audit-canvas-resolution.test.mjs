test('production-bound audit rejects profile byte drift even when JSON data is unchanged', async (t) => {
  const fixture = await createFixture(t);
  const original = await readFile(fixture.profilePath);
  await writeFile(fixture.profilePath, Buffer.concat([
    original.subarray(0, original.length - 1),
    Buffer.from('  \n'),
  ]));
  await assert.rejects(
    auditCanvasResolution({
      projectRoot: fixture.root,
      profilePath: fixture.profilePath,
      scope: 'production-five',
      contract: fixture.contract,
    }),
    /profile file SHA-256 is outside the audit contract/u,
  );
});

test('write/check mode byte-compares a recomputed report and rejects drift', async (t) => {
  const fixture = await createFixture(t);
  const document = await auditCanvasResolution({
    projectRoot: fixture.root,
    profilePath: fixture.profilePath,
    scope: 'pilot',
    contract: fixture.contract,
  });
  const outputPath = path.join(fixture.root, 'output', 'audit.json');
  const written = await writeOrCheckReport({
    document,
    outputPath,
    projectRoot: fixture.root,
  });
  assert.equal(written.operation, 'write');
  const identical = await writeOrCheckReport({
    document,
    outputPath,
    projectRoot: fixture.root,
  });
  assert.equal(identical.operation, 'existing-identical');
  const checked = await writeOrCheckReport({
    document,
    outputPath,
    check: true,
    projectRoot: fixture.root,
  });
  assert.equal(checked.operation, 'check');
  const current = await readFile(outputPath);
  await writeFile(outputPath, Buffer.concat([current, Buffer.from(' ')]));
  await assert.rejects(
    writeOrCheckReport({
      document,
      outputPath,
      projectRoot: fixture.root,
    }),
    /refusing to overwrite immutable audit evidence/u,
  );
  await assert.rejects(
    writeOrCheckReport({
      document,
      outputPath,
      check: true,
      projectRoot: fixture.root,
    }),
    /output is stale/u,
  );
});

test('argument parser supports the audit CLI and closes invalid check usage', () => {
  assert.deepEqual(
    parseArguments([
      '--scope=pilot',
      '--profile',
      'profile.json',
      '--output=report.json',
      '--check',
    ]),
    {
      profilePath: 'profile.json',
      scope: 'pilot',
      outputPath: 'report.json',
      check: true,
      help: false,
    },
  );
  assert.throws(
    () => parseArguments(['--scope', 'all']),
    /expected pilot or production-five/u,
  );
  assert.throws(
    () => parseArguments(['--check']),
    /requires --output/u,
  );
  assert.throws(
    () => parseArguments(['--unknown']),
    /unknown argument/u,
  );
});
