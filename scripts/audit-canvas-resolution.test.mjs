async function createFixture(t) {
  await mkdir(TEST_TEMP_PARENT, {recursive: true});
  const root = await mkdtemp(
    path.join(TEST_TEMP_PARENT, '.canvas-resolution-audit-test-'),
  );
  t.after(async () => rm(root, {recursive: true, force: true}));
  const definitions = [
    {
      animationId: 'fixture-renderer-a',
      releaseId: 'fixture-release-1',
      source: fixtureRenderer({
        animationId: 'fixture-renderer-a',
        bitmap: true,
        vectorFont: true,
        fillText: true,
        actualFilter: true,
      }),
    },
    {
      animationId: 'fixture-renderer-b',
      releaseId: 'fixture-release-1',
      source: fixtureRenderer({
        animationId: 'fixture-renderer-b',
        vectorFont: true,
      }),
    },
    {
      animationId: 'fixture-renderer-c',
      releaseId: 'fixture-release-2',
      source: fixtureRenderer({
        animationId: 'fixture-renderer-c',
        bitmap: true,
        vectorFont: false,
      }),
    },
  ];
  const entries = [];
  for (const definition of definitions) {
    const relativePath = `${definition.animationId}/canvas-renderer.js`;
    const assetPath = `courses/${relativePath}`;
    const absolutePath = path.join(
      root,
      'apps/web/public/flash-assets/courses',
      definition.animationId,
      'canvas-renderer.js',
    );
    await mkdir(path.dirname(absolutePath), {recursive: true});
    const bytes = Buffer.from(definition.source);
    await writeFile(absolutePath, bytes);
    entries.push({
      assetPath,
      relativePath,
      storageRoot: 'public',
      releaseId: definition.releaseId,
      bytes: bytes.length,
      sha256: digest(bytes),
    });
  }
  entries.sort((left, right) => left.assetPath.localeCompare(right.assetPath));
  const checksumSetSha256 = computeProfileChecksumSet(entries);
  const profile = {
    schemaVersion: 1,
    profileId: 'fixture-current-js-production-assets-v1',
    generatedBy: 'fixture',
    approvalScope: 'fixture-production-five',
    approvedReleaseIds: ['fixture-release-1', 'fixture-release-2'],
    counts: {public: 3, serverAudio: 0, total: 3},
    checksumSetSha256,
    entries,
  };
  const profilePath = path.join(root, 'fixture-profile.json');
  const profileBytes = Buffer.from(`${JSON.stringify(profile, null, 2)}\n`);
  await writeFile(profilePath, profileBytes);
  return {
    root,
    profilePath,
    contract: fixtureContract(checksumSetSha256, digest(profileBytes)),
    definitions,
  };
}

test('small renderer fixture separates bitmap/filter facts from safety helpers', () => {
  const source = fixtureRenderer({
    animationId: 'fixture-renderer-a',
    bitmap: true,
    fillText: true,
    actualFilter: true,
  });
  const analysis = analyzeRendererSource({
    animationId: 'fixture-renderer-a',
    releaseId: 'fixture-release-1',
    source,
    contract: fixtureContract(null),
  });
  assert.deepEqual(analysis.nativeCanvas, {
    guard: {width: 800, height: 600, occurrenceCount: 1},
    rootTransform: [1, 0, 0, 1, 0, 0],
    contractMatched: true,
  });
  assert.equal(analysis.embeddedBitmaps.occurrenceCount, 1);
  assert.equal(analysis.embeddedBitmaps.uniqueDecodedImageCount, 1);
  assert.equal(analysis.embeddedBitmaps.excludedSafetyLiteralCount, 1);
  assert.deepEqual(analysis.embeddedBitmaps.images[0].mime, ['image/png']);
  assert.deepEqual(
    analysis.embeddedBitmaps.images[0].detectedMime,
    ['image/png'],
  );
  assert.equal(analysis.embeddedBitmaps.images[0].intrinsicWidth, 1);
  assert.equal(analysis.embeddedBitmaps.images[0].intrinsicHeight, 1);
  assert.equal(
    analysis.embeddedBitmaps.images[0].disposition,
    'preserve-source-bitmap-and-mark-resolution-ceiling',
  );
  assert.equal(
    analysis.embeddedBitmaps.images[0].maxAuthoredDrawArea.status,
    'not-statically-proven',
  );
  assert.equal(analysis.vectorFonts.functionOccurrenceCount, 1);
  assert.deepEqual(analysis.vectorFonts.functionNames, ['font12']);
  assert.equal(analysis.fillText.occurrenceCount, 1);
  assert.equal(analysis.filters.helperDefinitionCount, 3);
  assert.equal(analysis.filters.helperInternalCallCount, 2);
  assert.equal(analysis.filters.actualPlacementCount, 1);
  assert.deepEqual(analysis.filters.actualPlacements, [
    {method: 'glow', occurrenceCount: 1},
  ]);
});

