/** One successful registered HFR asset verification. No byte/hash assertion is
 * skipped on a miss; hits require the complete closed input metadata unchanged. */
import assert from 'node:assert/strict';
import {lstatSync,readdirSync,realpathSync} from 'node:fs';
import path from 'node:path';
import {resolveG678PhysicalPath,resolveG678HistoricalEvidencePath} from './g678-life-root-binding-v1.mjs';
import {readOrdinary,readJsonPin,REGISTRY,DISPATCH} from './g678-admission-proof.mjs';

const ACTIVATION='apps/web/lib/g678-admission-activation.ts';
const RUNTIME='packages/demos/src/hfr';
// Same nanosecond identity fields as the existing admission read observation.
const FIELDS=['dev','ino','mode','size','mtimeNs','ctimeNs','nlink'];
const same=(a,b)=>FIELDS.every(k=>a[k]===b[k]);
let success=null;

function physical(file,kind){
 assert(realpathSync(file)===file,'HFR cached verification input must remain physical');
 const stat=lstatSync(file,{bigint:true});
 assert(kind==='directory'?stat.isDirectory():stat.isFile()&&stat.nlink===1n&&stat.size<=64n*1024n*1024n,'HFR cached verification input kind');
 return Object.fromEntries(FIELDS.map(k=>[k,stat[k]]));
}
function checkSnapshot(snapshot){for(const [file,{kind,metadata}] of snapshot)assert(same(metadata,physical(file,kind)),'HFR cached verification input changed: '+file);}
function freeze(value){if(value&&typeof value==='object'){for(const item of Object.values(value))freeze(item);Object.freeze(value);}return value;}

function checkActivation(root,indexPin){
 // The imported activation must still equal the real generated activation.
 const activation=readOrdinary(root,ACTIVATION).toString();
 assert.equal(activation,'// Reviewed split-proof activation. Generated by the admission build, not a page renderer.\nexport const G678_ADMISSION_INDEX = '+JSON.stringify(indexPin,null,2)+' as const;\n','HFR actual activation differs from loaded index');
}
function closedInputs(root,animationId,packetPin,indexPin){
 checkActivation(root,indexPin);
 const index=readJsonPin(root,indexPin),selected=index.pages.filter(p=>p.animationId===animationId);
 if(selected.length===0)return null; // Unregistered candidates never create a cache entry.
 assert.equal(selected.length,1,'HFR unique selected proof');
 const proofPin=selected[0].proof,host=readJsonPin(root,index.host),proof=readJsonPin(root,proofPin),packet=readJsonPin(root,packetPin);
 assert.equal(proof.animationId,animationId);assert.deepEqual(proof.packet.freezeManifest,packetPin);
 const closure=readJsonPin(root,packet.entry.artifacts.closure),snapshot=new Map();
 function directory(file){
  const old=snapshot.get(file);if(old){assert.equal(old.kind,'directory');return;}
  snapshot.set(file,{kind:'directory',metadata:physical(file,'directory')});
 }
 function add(boundRoot,pin,historicalEvidence=false){
  boundRoot=(historicalEvidence?resolveG678HistoricalEvidencePath:resolveG678PhysicalPath)(boundRoot,root);
  const relative=pin.path;assert(typeof relative==='string'&&!path.isAbsolute(relative)&&!relative.includes('\\')&&relative.split('/').every(p=>p&&p!=='.'&&p!=='..'),'HFR cache bounded relative input');
  const base=path.resolve(boundRoot);assert.equal(base,boundRoot,'HFR cache exact source root');directory(base);
  const file=path.resolve(base,relative);let parent=path.dirname(file);
  while(parent!==base){assert(parent.startsWith(base+path.sep));directory(parent);parent=path.dirname(parent);}
  const old=snapshot.get(file);if(old){assert.equal(old.kind,'file');return;}
  snapshot.set(file,{kind:'file',metadata:physical(file,'file')});
 }
 function inventory(relative){
  const dir=path.resolve(root,relative);directory(dir);
  for(const item of readdirSync(dir,{withFileTypes:true})){
   const member=relative+'/'+item.name;
   if(item.isDirectory())inventory(member);
   else {assert(item.isFile()&&!item.isSymbolicLink(),'HFR cache ordinary inventory member');add(root,{path:member});}
  }
 }
 // Complete common reader closure, raw transaction/dispatch and private artifact
 // reader inputs. Capture both prior snapshot and current transition paths.
 for(const p of [{path:ACTIVATION},{path:REGISTRY},...DISPATCH.map(path=>({path})),indexPin,index.host,proofPin,packetPin,...host.files,...proof.files,...proof.legacyInputs,...packet.integrity.files])add(root,p);
 for(const group of [host.legacyPageHostPromotions??[],host.legacyInputTransitions??[],host.historicalRoutes??[]])for(const t of group)for(const k of ['current','snapshot'])if(t[k])add(root,t[k]);
 for(const item of proof.external)add(item.root,item.pin,true);
 for(const k of ['module','generated','data','closure'])add(root,packet.entry.artifacts[k]);
 for(const p of [closure.releaseManifest,...closure.compiler,...closure.runtime,...closure.host,...closure.media])add(root,p);
 for(const p of [closure.source,closure.sourceXml,...closure.sourceAudio])add(closure.sourceRoot,p);
 const member=path.posix.dirname(packet.entry.artifacts.data.path);
 inventory(path.posix.dirname(path.posix.dirname(member))+'/compiler');
 inventory(member+'/media');inventory(RUNTIME);
 return snapshot;
}

/** The caller must perform its existing development/local-preview guards before
 * every call, including hits. verify executes its unchanged complete reader. */
export async function withRegisteredHfrAsset({root,animationId,packetPin,indexPin,verify},readAsset){
 resolveG678PhysicalPath(root); // Enforce the current source binding on cache hits too.
 const key=JSON.stringify({root,animationId,packetPin,indexPin});let entry=success;
 if(entry?.key===key){
  try{checkSnapshot(entry.snapshot);}catch{if(success===entry)success=null;entry=null;}
 }else{success=null;entry=null;}
 try{
  if(!entry){
   const snapshot=closedInputs(root,animationId,packetPin,indexPin);
   const value=verify(); // Original full hash, source, host, proof and registry validation.
   if(!value.registered)return await readAsset(value);
   // Activation is imported by the old reader: close its initial text-read to
   // metadata-capture window before sealing the successful result.
   checkActivation(root,indexPin);
   assert(snapshot,'Registered HFR assets require a selected proof');checkSnapshot(snapshot);
   entry={key,snapshot,value:freeze(structuredClone(value))};success=entry;
  }
  const result=await readAsset(entry.value); // Existing requested-asset hash and path checks.
  checkSnapshot(entry.snapshot); // Reject a change while asynchronous asset bytes were read.
  if(result==null&&success===entry)success=null;
  return result;
 }catch(error){if(success===entry)success=null;throw error;}
}
