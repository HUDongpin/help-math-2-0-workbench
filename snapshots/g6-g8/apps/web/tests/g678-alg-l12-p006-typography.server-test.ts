import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import test from 'node:test';
import {algL12P006Typography} from '../lib/g678-alg-l12-p006-typography.server';
import {GET} from '../app/flash-assets/g678-local/shared-alg001-l12-p006/typography-renderer.js/route';
import meta from '../../../migrations/shared-alg001-l12-p006/typography-v1/runtime-meta.json';

const env: Record<string, string | undefined> = process.env;
const keys = ['NODE_ENV', 'VERCEL_ENV', 'HELP_MATH_G678_LOCAL_PREVIEW',
  'HELP_MATH_G678_LOCAL_PREVIEW_BIND', 'HELP_MATH_G678_SOURCE_ROOT'] as const;
async function local(run: () => void | Promise<void>) {
  const before = Object.fromEntries(keys.map(key => [key, env[key]]));
  try {
    env.NODE_ENV = 'development'; delete env.VERCEL_ENV;
    env.HELP_MATH_G678_LOCAL_PREVIEW = '1'; env.HELP_MATH_G678_LOCAL_PREVIEW_BIND = '127.0.0.1';
    env.HELP_MATH_G678_SOURCE_ROOT = '/Volumes/WestWorld/HELP MATH Related Files/AWS Grade-Classified Courseware';
    await run();
  } finally {
    for (const key of keys) {if (before[key] === undefined) delete env[key]; else env[key] = before[key];}
  }
}
const url = `http://127.0.0.1:43218/flash-assets/g678-local/shared-alg001-l12-p006/typography-renderer.js?sha256=${meta.runtimeSha256}`;
function request(target = url, headers: Record<string, string> = {}) {
  return new Request(target, {headers: {host: '127.0.0.1:43218',
    referer: 'http://127.0.0.1:43218/en/migration-status/g678-calibration/shared-alg001-l12-p006',
    origin: 'http://127.0.0.1:43218', 'sec-fetch-site': 'same-origin',
    'sec-fetch-mode': 'cors', 'sec-fetch-dest': 'script', ...headers}});
}
test('P006 typography asset is exact private source-bound generated bytes', async () => local(async () => {
  const asset = algL12P006Typography();
  assert.equal(asset.sha256, meta.runtimeSha256); assert.equal(asset.bytes.length, meta.runtimeBytes);
  assert.equal(createHash('sha256').update(asset.bytes).digest('hex'), meta.runtimeSha256);
  const response = await GET(request());
  assert.equal(response.status, 200);
  assert.equal(response.headers.get('content-type'), 'text/javascript; charset=utf-8');
  assert.equal(response.headers.get('cache-control'), 'private, no-store, max-age=0');
  assert.match(response.headers.get('x-robots-tag') ?? '', /noindex/);
  assert.equal(createHash('sha256').update(new Uint8Array(await response.arrayBuffer())).digest('hex'), meta.runtimeSha256);
  asset.bytes.fill(0);
  assert.equal(createHash('sha256').update(algL12P006Typography().bytes).digest('hex'), meta.runtimeSha256);
}));
test('P006 typography stays unavailable outside exact local scope', async () => {
  const cases: Array<[typeof keys[number], string | undefined]> = [
    ['NODE_ENV', 'production'], ['VERCEL_ENV', 'preview'], ['HELP_MATH_G678_LOCAL_PREVIEW', undefined],
    ['HELP_MATH_G678_LOCAL_PREVIEW_BIND', '0.0.0.0'], ['HELP_MATH_G678_SOURCE_ROOT', '/nonexistent'],
  ];
  for (const [key, value] of cases) await local(async () => {
    if (value === undefined) delete env[key]; else env[key] = value;
    assert.throws(() => algL12P006Typography());
    assert.equal((await GET(request())).status, 404);
  });
});
test('P006 typography asset denies query, origin, method, range and path drift', async () => local(async () => {
  const cases = [request(url.split('?')[0]), request(url + '&extra=1'), request(url + '&sha256=x'),
    request(url.replace(meta.runtimeSha256, 'wrong')), request(url.replace('typography-renderer', 'canvas-renderer')),
    request(url, {host: 'helpmath.ai'}), request(url, {origin: 'https://example.com'}),
    request(url, {range: 'bytes=0-5'}), request(url, {'sec-fetch-site': 'cross-site'}),
    request(url, {'sec-fetch-mode': 'navigate'}), new Request(url, {method: 'POST', headers: request().headers})];
  for (const req of cases) {
    const res = await GET(req); assert.equal(res.status, 404);
    assert.equal((await res.arrayBuffer()).byteLength, 0);
  }
}));
