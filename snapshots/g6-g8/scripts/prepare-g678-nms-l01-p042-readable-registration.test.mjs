import assert from 'node:assert/strict';
import {lstat, readFile, symlink, writeFile} from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import {REGISTRY, PRIOR, PLANNER, PROPOSED_FREEZE, PROPOSED_FRAGMENT, publish378Preparation, binding}
  from './prepare-g678-nms-l01-p042-readable-registration.mjs';
import {temporary, snapshot, seed} from './g678-nms-l01-p042-readable-registration-test-fixtures.mjs';

test('exclusive 378 preparation writes3 readonly files; two checks preserve bytes/inodes and live registry', async t => {
  const f = await temporary(t), original = await snapshot(f.root);
  assert.equal(await publish378Preparation(f), 3);
  const after = await snapshot(f.root), added = after.filter(r => !original.some(p => p.path === r.path));
  assert.deepEqual(added.map(r => r.path).sort(), [PRIOR.registry.path, PROPOSED_FREEZE, PROPOSED_FRAGMENT].sort());
  assert.ok(added.every(r => (Number(r.mode) & 0o222) === 0));
  assert.deepEqual(after.filter(r => original.some(p => p.path === r.path)), original);
  for (let i = 0; i < 2; i++) assert.equal(await publish378Preparation({...f, check: true}), 0);
  assert.deepEqual(await snapshot(f.root), after);
  await assert.rejects(publish378Preparation(f), /Exclusive 378 output exists/);
  assert.deepEqual(await snapshot(f.root), after);
});
test('immutable witness supports checks after live registry activation; existing exact witness is not overwritten', async t => {
  const f = await temporary(t);
  await seed(f.root, [[PRIOR.registry.path, f.witnessBytes, 0o444]]);
  const witness = (await snapshot(f.root)).find(r => r.path === PRIOR.registry.path);
  assert.equal(await publish378Preparation(f), 2);
  assert.deepEqual((await snapshot(f.root)).find(r => r.path === PRIOR.registry.path), witness);
  await writeFile(path.join(f.root, REGISTRY), f.result.nextRegistryBytes);
  const before = await snapshot(f.root); assert.equal(await publish378Preparation({...f, check: true}), 0);
  assert.deepEqual(await snapshot(f.root), before);
});
test('output conflict and stale/writable/symlink witness fail before any additional output writes', async t => {
  for (const kind of ['output', 'stale', 'writable', 'symlink']) {
    const f = await temporary(t);
    if (kind === 'output') await writeFile(path.join(f.root, PROPOSED_FRAGMENT), 'existing authority\n', {flag: 'wx'});
    if (kind === 'stale') await writeFile(path.join(f.root, PRIOR.registry.path), '{}\n', {flag: 'wx', mode: 0o444});
    if (kind === 'writable') await writeFile(path.join(f.root, PRIOR.registry.path), f.witnessBytes, {flag: 'wx'});
    if (kind === 'symlink') await symlink(path.join(f.root, REGISTRY), path.join(f.root, PRIOR.registry.path));
    const before = await snapshot(f.root); await assert.rejects(publish378Preparation(f));
    assert.deepEqual(await snapshot(f.root), before);
    await assert.rejects(lstat(path.join(f.root, PROPOSED_FREEZE)), {code: 'ENOENT'});
  }
});
test('forged result or physical planner/live-registry drift cannot publish a prepared authority', async t => {
  for (const kind of ['result', 'planner', 'registry']) {
    const f = await temporary(t);
    if (kind === 'result') f.result = {...f.result, freezeBytes: Buffer.from('{}\n')};
    if (kind === 'planner') await writeFile(path.join(f.root, PLANNER), '// changed planner\n');
    if (kind === 'registry') await writeFile(path.join(f.root, REGISTRY), Buffer.concat([f.witnessBytes, Buffer.from('\n')]));
    const before = await snapshot(f.root); await assert.rejects(publish378Preparation(f));
    assert.deepEqual(await snapshot(f.root), before);
    await assert.rejects(lstat(path.join(f.root, PRIOR.registry.path)), {code: 'ENOENT'});
  }
});
test('missing preparation or changed generated bytes are rejected by a write-free check', async t => {
  const f = await temporary(t), first = await snapshot(f.root);
  await assert.rejects(publish378Preparation({...f, check: true}), {code: 'ENOENT'});
  assert.deepEqual(await snapshot(f.root), first);
  await publish378Preparation(f); const original = await readFile(path.join(f.root, PROPOSED_FRAGMENT));
  // Deliberate test-owned evidence corruption, never a real workspace artifact.
  const {chmod} = await import('node:fs/promises'); await chmod(path.join(f.root, PROPOSED_FRAGMENT), 0o644);
  await writeFile(path.join(f.root, PROPOSED_FRAGMENT), Buffer.concat([original, Buffer.from('\n')]));
  await chmod(path.join(f.root, PROPOSED_FRAGMENT), 0o444);
  const before = await snapshot(f.root); await assert.rejects(publish378Preparation({...f, check: true}), /Prepared 378 drift/);
  assert.deepEqual(await snapshot(f.root), before);
  assert.deepEqual(binding(PRIOR.registry.path, await readFile(path.join(f.root, PRIOR.registry.path))), PRIOR.registry);
});

