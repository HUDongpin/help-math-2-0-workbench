"""Derive candidate rectangular hit intersections from verified source paths."""
from pathlib import Path
import hashlib
import json
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
AUDIT = ROOT / 'migrations/shared-alg001-l12-p006/audit'
raw = (AUDIT / 'ffdec-26.2.1/movie.xml').read_bytes()
assert hashlib.sha256(raw).hexdigest() == '60c835b77135803e0699aa6580650413ec9591d14f17dbe70d01365cea28a77a'
movie = ET.fromstring(raw)
ir = json.loads((AUDIT / 'display-ir-v1.json').read_text())
assert ir['xmlSha256'] == hashlib.sha256(raw).hexdigest()
assert hashlib.sha256((AUDIT / 'display-ir-v1.json').read_bytes()).hexdigest() == '80456d15ae0ee6ff68af646eed0d2e31b970e76c769e0dcd7d9ae2112ecc3436'
for button_id in [48, 49, 50, 51]:
    button = next(n for n in movie.find('tags') if n.get('buttonId') == str(button_id))
    records = button.findall('./characters/item')
    assert len(records) == 1 and records[0].get('characterId') == '47'
    assert records[0].get('buttonStateHitTest') == 'true'
    matrix = records[0].find('placeMatrix')
    assert matrix.get('hasScale') == matrix.get('hasRotate') == 'false'
    assert matrix.get('translateX') == matrix.get('translateY') == '0'


def rect(records):
    records = list(records)
    assert len(records) == 6 and records[0].get('type') == 'StyleChangeRecord'
    x, y = int(records[0].get('moveDeltaX')), int(records[0].get('moveDeltaY'))
    points = [(x, y)]
    for edge in records[1:5]:
        assert edge.get('type') == 'StraightEdgeRecord'
        dx, dy = int(edge.get('deltaX', '0')), int(edge.get('deltaY', '0'))
        assert (dx == 0) != (dy == 0)
        x, y = x + dx, y + dy
        points.append((x, y))
    assert points[0] == points[-1]
    xs, ys = sorted(set(p[0] for p in points)), sorted(set(p[1] for p in points))
    assert len(xs) == len(ys) == 2
    assert set(points) == {(x, y) for x in xs for y in ys}
    return [xs[0], ys[0], xs[1], ys[1]]


def shape(id):
    return next(n for n in movie.find('tags') if n.get('shapeId') == str(id))


rects = {id: rect(shape(id).findall('./shapes/shapeRecords/item')) for id in [1, 47, 52]}
morph = next(n for n in movie.find('tags') if n.get('characterId') == '43')
start = rect(morph.findall('./startEdges/shapeRecords/item'))
end = rect(morph.findall('./endEdges/shapeRecords/item'))


def transformed(bounds, matrix):
    m = {k: float(v) for k, v in matrix.items()}
    assert m['rotateSkew0'] == m['rotateSkew1'] == 0 and m['scaleX'] > 0 and m['scaleY'] > 0
    return [bounds[0] * m['scaleX'] + m['translateX'], bounds[1] * m['scaleY'] + m['translateY'],
            bounds[2] * m['scaleX'] + m['translateX'], bounds[3] * m['scaleY'] + m['translateY']]


root_frame = ir['timelines'][0]['frames'][5]
parent = next(s for s in root_frame if s['characterId'] == 53)['matrix']
for key, expected in [('scaleX', '1'), ('scaleY', '1'), ('rotateSkew0', '0'), ('rotateSkew1', '0')]:
    assert parent[key] == expected
frames = ir['timelines'][1]['frames']
result = []
for frame, entries in enumerate(frames, 1):
    hits = []
    for button in [e for e in entries if e['characterId'] in [48, 49, 50, 51]]:
        bounds = transformed(rects[47], button['matrix'])
        for mask in [e for e in entries if e['clipDepth'] is not None and e['depth'] < button['depth'] <= e['clipDepth']]:
            if mask['characterId'] == 43:
                ratio = mask['ratio'] / 65535
                geometry = [a + (b - a) * ratio for a, b in zip(start, end)]
            else:
                assert mask['characterId'] in [1, 52]
                geometry = rects[mask['characterId']]
            clip = transformed(geometry, mask['matrix'])
            bounds = [max(bounds[0], clip[0]), max(bounds[1], clip[1]), min(bounds[2], clip[2]), min(bounds[3], clip[3])]
        if bounds[0] < bounds[2] and bounds[1] < bounds[3]:
            native = [(v + float(parent['translateX' if i % 2 == 0 else 'translateY'])) / 20 for i, v in enumerate(bounds)]
            hits.append({'characterId': button['characterId'], 'rect': native})
    result.append(hits)
data = {'sourceSha256': ir['sourceSha256'], 'authority': 'candidate-source-geometry; original hit testing unverified', 'frames': result}
output = ROOT / 'packages/demos/src/generated/alg-l12-p006-hit-spec.ts'
text = '// Generated by scripts/build-g678-alg-l12-p006-hit-spec.py; do not edit.\nexport const P006_HIT_SPEC = ' + json.dumps(data, separators=(',', ':')) + ' as const;\n'
assert len(sys.argv) == 2 and sys.argv[1] in ('--write', '--check')
if sys.argv[1] == '--check':
    assert output.read_text() == text
else:
    output.parent.mkdir(exist_ok=True)
    with output.open('x') as handle:
        handle.write(text)
