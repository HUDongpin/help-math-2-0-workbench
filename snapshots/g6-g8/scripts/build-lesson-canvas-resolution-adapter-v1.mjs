const HASH = /^[a-f0-9]{64}$/;
const PREFIX = '__hmResolutionV1';
const RW_CANDIDATE_SOURCES = Object.freeze({
  'course-g03-l09-rw-003':'14c44b7b879f74fe4fca5a67716d1ec8f2e7dce7b6b092ab172f6f36f22f977a',
  'course-g03-l09-rw-004':'00b3e785d8c2ab4a3a43e85d8c4ccf2c283ba1dae54c99d47438a2fbfb7b26b9',
  'course-g03-l09-rw-005':'3ec32169303bf9aee9cf40ce63cddd651093b5f7f5e87df68778798f50a86dc5',
});
const sha = value => createHash('sha256').update(value).digest('hex');
const assert = (condition, message) => {if (!condition) throw new Error(message);};
function walk(node, visit, parent = null) {
  if (!node || typeof node !== 'object') return;
  if (node.type) visit(node, parent);
  for (const value of Object.values(node)) {
    if (Array.isArray(value)) for (const child of value) walk(child, visit, node);
    else if (value && typeof value === 'object') walk(value, visit, node);
  }
}
function constant(node) {
  if (node.type === 'Literal') return node.value;
  if (node.type === 'UnaryExpression' && node.operator === '-') return -constant(node.argument);
  if (node.type === 'ArrayExpression') return node.elements.map(constant);
  if (node.type === 'ObjectExpression') return Object.fromEntries(node.properties.map(property => {
    assert(property.type === 'Property' && !property.computed, 'Nonliteral source metadata');
    return [property.key.name ?? property.key.value, constant(property.value)];
  }));
  throw new Error('Nonliteral source metadata');
}
const member = (node, object, property) => node?.type === 'MemberExpression' && !node.computed
  && node.object.name === object && node.property.name === property;

/** A derived, independently registered variant. The old generator and asset
 * bytes are untouched. This adds only a declared integer backing scale; frame,
 * scenario, seed, source transforms and text observation logic are preserved. */
export function buildLessonCanvasResolutionAdapter({javascript, expectedSha256, variantId}) {
  assert(typeof javascript === 'string' && HASH.test(expectedSha256) && sha(javascript) === expectedSha256, 'Resolution input SHA mismatch');
  const candidateBundleLineage = javascript.startsWith('/* Generated by scripts/build-g3-l05-page-only-candidate-bundle.mjs. */');
  assert(candidateBundleLineage || javascript.startsWith('/* Generated by scripts/build-safe-ffdec-canvas-adapter.mjs. */'), 'Unsupported safe adapter lineage');
  assert(!javascript.includes('ACTIVE_BEHAVIOR_COMPOSITE'), 'Behavior composite requires a maintained resolution adapter');
  assert(!javascript.includes(PREFIX), 'Resolution adapter is already transformed');
  assert(/^[a-z0-9][a-z0-9-]+$/.test(variantId), 'Invalid resolution variant ID');
  const ast = parse(javascript, {ecmaVersion: 2022, sourceType: 'script'});
  let metadataNode, render, registration, registryName;
  const edits = [], replacement = (node, value) => edits.push({start: node.start, end: node.end, value});
  walk(ast, (node) => {
    if (node.type === 'VariableDeclarator' && node.id.name === 'METADATA') metadataNode = node.init.arguments?.[0];
    if (node.type === 'FunctionDeclaration' && node.id.name === 'render') {assert(!render, 'Multiple render functions'); render = node;}
    if (node.type === 'VariableDeclarator' && node.id.name === 'registry' && node.init?.object?.name === 'global') registryName = node.init.property?.value;
    if (node.type === 'AssignmentExpression' && node.left.type === 'MemberExpression' && node.left.object.name === 'registry'
      && node.right.type === 'CallExpression') {assert(!registration, 'Multiple registrations'); registration = node;}
    if (node.type === 'Identifier' && ['eval','Function','fetch','XMLHttpRequest','WebSocket','setInterval','setTimeout','requestAnimationFrame'].includes(node.name)) throw new Error(`Unsafe or clock-bearing input: ${node.name}`);
  });
  assert(metadataNode && render && registration && ['HELP_MATH_CANVAS_ASSETS','HELP_MATH_TEXT_CANVAS_ASSETS'].includes(registryName), 'Unsupported resolution adapter envelope');
  const metadata = constant(metadataNode), {width, height} = metadata.stage ?? {};
  if (candidateBundleLineage) assert(RW_CANDIDATE_SOURCES[metadata.animationId] === metadata.sourceSwfSha256,
    'Candidate-bundle resolution conversion is restricted to the three verified RW sources');
  assert(HASH.test(metadata.sourceSwfSha256) && [width,height].every(value => Number.isFinite(value) && value > 0 && Number.isSafeInteger(Math.ceil(value * 2))), 'Invalid authored stage');
  assert((metadata.renderScale ?? 1) === 1, 'Resolution conversion requires the original 1x adapter');
  const oldKey = registration.left.property.value;
  assert(typeof oldKey === 'string' && oldKey !== variantId, 'Resolution variant must have a separate registry key');
  assert(render.params.map(parameter => parameter.name).join(',') === 'targetCanvas,request', 'Unexpected render parameters');
  let guard, transform, fill;
  for (const statement of render.body.body) {
    const condition = statement.type === 'IfStatement' && statement.test;
    if (condition?.type === 'LogicalExpression' && condition.operator === '||'
      && condition.left.type === 'BinaryExpression' && condition.left.operator === '!=='
      && member(condition.left.left, 'targetCanvas','width') && condition.left.right.value === width
      && condition.right.type === 'BinaryExpression' && condition.right.operator === '!=='
      && member(condition.right.left,'targetCanvas','height') && condition.right.right.value === height) guard = condition;
    const call = statement.type === 'ExpressionStatement' && statement.expression;
    if (call?.type === 'CallExpression' && member(call.callee,'ctx','setTransform')) {
      assert(JSON.stringify(call.arguments.map(constant)) === '[1,0,0,1,0,0]', 'Source root transform is not unscaled');
      assert(!transform, 'Ambiguous root transform'); transform = call;
    }
    if (call?.type === 'CallExpression' && member(call.callee,'ctx','fillRect')) {
      assert(call.arguments.length === 4 && call.arguments[0].value === 0 && call.arguments[1].value === 0
        && member(call.arguments[2],'targetCanvas','width') && member(call.arguments[3],'targetCanvas','height'), 'Unexpected source background fill');
      assert(!fill, 'Ambiguous source background'); fill = call;
    }
  }
  assert(guard && transform && fill, 'Unsupported source backing guard/transform/fill');
  edits.push({start:render.body.start+1,end:render.body.start+1,value:`\nvar ${PREFIX}Scale = request && request.renderScale !== undefined ? request.renderScale : 1;\nif (${PREFIX}Scale !== 1 && ${PREFIX}Scale !== 2) throw new Error("Unsupported lesson Canvas resolution scale");\n`});
  replacement(guard, `targetCanvas.width !== Math.ceil(${width} * ${PREFIX}Scale) || targetCanvas.height !== Math.ceil(${height} * ${PREFIX}Scale)`);
  replacement(transform, `ctx.setTransform(${PREFIX}Scale,0,0,${PREFIX}Scale,0,0)`);
  replacement(fill, `ctx.fillRect(0,0,targetCanvas.width/${PREFIX}Scale,targetCanvas.height/${PREFIX}Scale)`);
  walk(ast, (node,parent) => {
    if (node.type !== 'Literal') return;
    if (node.value === registryName && ((parent?.type === 'MemberExpression' && parent.object.name === 'global')
      || (parent?.type === 'CallExpression' && parent.arguments[0]?.name === 'global'))) {
      replacement(node, JSON.stringify('HELP_MATH_HD_CANVAS_ASSETS'));
    }
    if (node.value === oldKey && ((parent?.type === 'MemberExpression' && parent.object.name === 'registry')
      || (parent?.type === 'CallExpression' && parent.arguments[0]?.name === 'registry'))) replacement(node,JSON.stringify(variantId));
  });
  const registryObject = registration.right.arguments[0];
  assert(registryObject?.type === 'ObjectExpression', 'Invalid source registry object');
  const metadataProperty = registryObject.properties.find(property => (property.key.name ?? property.key.value) === 'metadata');
  assert(metadataProperty, 'Missing registered metadata');
  const resolution = {schemaVersion:1,mode:'adaptive-integer',nativeWidth:width,nativeHeight:height,supportedScales:[1,2]};
  const provenance = {schemaVersion:1,kind:'lesson-canvas-resolution-adapter-v1',builderVersion:'1.0.0',acornVersion,
    variantId,originalRegistry:registryName,originalKey:oldKey,originalAnimationId:metadata.animationId,
    inputSha256:expectedSha256,inputBytes:Buffer.byteLength(javascript),sourceSwfSha256:metadata.sourceSwfSha256,
    resolution,defaultEnabled:false,originalRuntimeEvidence:false,modernizationComplete:false};
  replacement(metadataProperty.value,`Object.freeze(Object.assign({},${javascript.slice(metadataProperty.value.start,metadataProperty.value.end)},{resolution:Object.freeze(${JSON.stringify(resolution)}),resolutionVariant:Object.freeze(${JSON.stringify(provenance)})}))`);
  let result = '', cursor = 0;
  for (const edit of edits.sort((a,b) => a.start-b.start || a.end-b.end)) {
    assert(edit.start >= cursor, 'Overlapping resolution edits');
    result += javascript.slice(cursor,edit.start)+edit.value;cursor=edit.end;
  }
  result += javascript.slice(cursor);parse(result,{ecmaVersion:2022,sourceType:'script'});
  return {javascript:result,manifest:{...provenance,outputSha256:sha(result),outputBytes:Buffer.byteLength(result)}};
}

/** Create-exclusive output membership: source bytes and existing variants stay
 * intact, and --check never rewrites a receipt to make it current. */
export async function buildLessonCanvasResolutionFromSpec(specPath, {root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'), check = false} = {}) {
  root = await realpath(root);
  const safePath = relative => {
    assert(typeof relative === 'string' && relative && !path.isAbsolute(relative)
      && !relative.split(/[\\/]/).some(part => !part || part === '..' || part === '.'), 'Unsafe resolution artifact path');
    return path.join(root, relative);
  };
  const ordinary = async relative => {
    const target = safePath(relative), stat = await lstat(target);
    assert(stat.isFile() && !stat.isSymbolicLink() && (await realpath(target)).startsWith(root + path.sep), 'Resolution input must be an in-worktree ordinary file');
    return readFile(target);
  };
  const specBytes = await ordinary(specPath), spec = JSON.parse(specBytes);
  assert(spec.schemaVersion === 1 && spec.kind === 'lesson-canvas-resolution-spec-v1', 'Invalid resolution spec');
  assert(/^(?:work\/typography-v1|apps\/web\/public\/typography-v1)\//.test(spec.outputDirectory), 'Resolution output must be a dedicated typography directory');
  const source = await ordinary(spec.input.path);
  const result = buildLessonCanvasResolutionAdapter({javascript:source.toString('utf8'),expectedSha256:spec.input.sha256,variantId:spec.variantId});
  const manifest = {...result.manifest,spec:{path:specPath,sha256:sha(specBytes)},inputPath:spec.input.path};
  const files = {'canvas-renderer.js':result.javascript,'manifest.json':JSON.stringify(manifest,null,2)+'\n'};
  const output = safePath(spec.outputDirectory);
  let existing = false;
  try {const stat=await lstat(output);assert(stat.isDirectory()&&!stat.isSymbolicLink(),'Invalid existing resolution output');existing=true;}
  catch(error){if(error.code!=='ENOENT')throw error;}
  if(check || existing) {
    assert(existing, 'Resolution output is missing');
    for(const [name,content] of Object.entries(files)) assert((await ordinary(`${spec.outputDirectory}/${name}`)).toString('utf8')===content,'Resolution output is stale; preserve it and choose a new variant directory');
  } else {
    await mkdir(path.dirname(output),{recursive:true});
    assert((await realpath(path.dirname(output))).startsWith(root+path.sep),'Resolution output parent escapes the worktree');
    const staging=`${output}.staging-${randomUUID()}`;
    await mkdir(staging);
    for(const [name,content] of Object.entries(files)) await writeFile(path.join(staging,name),content,{flag:'wx'});
    // Never replace an existing candidate that appeared during generation.
    try {await lstat(output);throw new Error('Resolution output appeared while building');}
    catch(error){if(error.code!=='ENOENT')throw error;}
    await rename(staging,output);
  }
  return manifest;
}

if(import.meta.url===pathToFileURL(process.argv[1]??'').href){
  const args=process.argv.slice(2),index=args.indexOf('--spec');
  assert(index>=0&&args[index+1]&&args.every((value,position)=>position===index||position===index+1||value==='--check'),
    'Usage: node scripts/build-lesson-canvas-resolution-adapter-v1.mjs --spec <relative-spec.json> [--check]');
  buildLessonCanvasResolutionFromSpec(args[index+1],{check:args.includes('--check')})
    .then(manifest=>process.stdout.write(JSON.stringify(manifest,null,2)+'\n'))
    .catch(error=>{process.stderr.write(`${error.stack??error}\n`);process.exitCode=1;});
}
