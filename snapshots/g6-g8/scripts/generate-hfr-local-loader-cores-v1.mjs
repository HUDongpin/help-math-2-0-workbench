export function project(source, edits) {
  for (const [before, after] of edits) {
    assert.equal(source.split(before).length - 1, 1, `projection occurrence: ${before}`);
    source = source.replace(before, after);
  }
  return header + source;
}
export function renderCores(sourceRoot) {
  const texts = sources.map(pin => {
    const bytes = fs.readFileSync(path.join(sourceRoot, pin.path));
    assert.equal(bytes.length, pin.bytes, `source size: ${pin.path}`);
    assert.equal(hash(bytes), pin.sha256, `source hash: ${pin.path}`);
    return bytes.toString('utf8');
  });
  const outputs = [
    ['apps/web/components/animation-runtime-hfr-loader-core-v1.generated.tsx', project(texts[0], runtimeEdits)],
    ['apps/web/components/descriptor-driven-whole-lesson-player-hfr-core-v1.generated.tsx', project(texts[1], playerEdits)],
  ];
  for (const [, text] of outputs) {
    assert(!text.includes('loadClientAnimationModule'), 'no global loader symbol in core');
    assert(!text.includes('load-animation-module.client'), 'no global loader import in core');
  }
  return outputs;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [mode, ...args] = process.argv.slice(2);
  assert(['--write', '--check'].includes(mode), 'expected --write or --check');
  let sourceRoot = repositoryRoot, outputRoot = repositoryRoot;
  for (let index = 0; index < args.length; index += 2) {
    const option = args[index], value = args[index + 1];
    assert(value && ['--source-root', '--output-root'].includes(option), 'bounded path option');
    if (option === '--source-root') sourceRoot = path.resolve(value);
    else outputRoot = path.resolve(value);
  }
  const outputs = renderCores(sourceRoot);
  for (const [relative, text] of outputs) {
    const filename = path.join(outputRoot, relative);
    if (mode === '--check') assert.equal(fs.readFileSync(filename, 'utf8'), text, `projection drift: ${relative}`);
    else if (fs.existsSync(filename)) assert.equal(fs.readFileSync(filename, 'utf8'), text, `refuse generated drift: ${relative}`);
    else {
      fs.mkdirSync(path.dirname(filename), {recursive: true});
      fs.writeFileSync(filename, text, {flag: 'wx'});
    }
  }
  console.log(JSON.stringify({kind: 'source-locked-hfr-local-loader-cores-v1', mode, sources,
    outputs: outputs.map(([relative, text]) => ({path: relative, bytes: Buffer.byteLength(text), sha256: hash(text)}))}));
}
