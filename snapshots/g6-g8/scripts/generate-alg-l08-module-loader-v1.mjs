/** The current canonical registry is the sole membership source. This projection
 * contains only its ALG001 L8 loaders, in source-page order. Candidate files on
 * disk never become registrations through this generator. */
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [mode, ...args] = process.argv.slice(2);
assert(['--write', '--check'].includes(mode), 'expected --write or --check');
let sourceRoot = repositoryRoot, outputRoot = repositoryRoot;
for (let index = 0; index < args.length; index += 2) {
  const option = args[index], value = args[index + 1];
  assert(value && ['--source-root', '--output-root'].includes(option), 'bounded path option');
  if (option === '--source-root') sourceRoot = path.resolve(value);
  else outputRoot = path.resolve(value);
}
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const registryPath = 'packages/demos/private-current-js-registry.json';
const bytes = fs.readFileSync(path.join(sourceRoot, registryPath));
const registry = JSON.parse(bytes.toString('utf8'));
assert.equal(registry.schemaVersion, 2);
assert.equal(registry.registryScope, 'private-engineering');
assert(Array.isArray(registry.calibrations));
const entries = [], seen = new Set();
for (const calibration of registry.calibrations) {
  assert(Array.isArray(calibration.entries), 'calibration entries');
  for (const entry of calibration.entries) {
    if (!entry.key.startsWith('shared-alg001-l08-')) continue;
    assert(/^shared-alg001-l08-p\d{3}$/u.test(entry.key), 'L8 page key');
    const ordinal = Number(entry.key.slice(-3));
    assert(Number.isSafeInteger(ordinal) && ordinal >= 1 && ordinal <= 50, '50-page source range');
    assert(!seen.has(entry.key), 'unique L8 registration');
    assert.equal(calibration.deploymentScope, 'local-only');
    assert.equal(entry.maturity, 'private-current-js');
    assert(/^\.\/modules\/[a-z0-9-]+$/u.test(entry.module), 'literal module path');
    seen.add(entry.key);
    entries.push({key: entry.key, module: entry.module});
  }
}
assert(entries.length > 0, 'registered L8 module subset');
entries.sort((a, b) => a.key.localeCompare(b.key));
const text = `// Generated by scripts/generate-alg-l08-module-loader-v1.mjs; do not edit.
import type {AnimationModule} from '../../../packages/demos/src/contract';

type ModuleLoader = () => Promise<AnimationModule>;
const loaders: Readonly<Record<string, ModuleLoader>> =
  process.env.NODE_ENV === 'production'
    ? Object.freeze({})
    : Object.freeze({
${entries.map(entry => `      '${entry.key}': () => import('../../../packages/demos/src/${entry.module.slice(2)}').then(({default: animationModule}) => Object.freeze({...animationModule, maturity: 'private-current-js' as const})),`).join('\n')}
    });

/** Descriptor availability and the existing local routes govern access. */
export async function loadAlgL08AnimationModuleV1(key: string): Promise<AnimationModule | undefined> {
  if (process.env.NODE_ENV === 'production' || !Object.hasOwn(loaders, key)) return undefined;
  return loaders[key]!();
}
`;
const relative = 'apps/web/lib/alg-l08-module-loader-v1.generated.ts';
const filename = path.join(outputRoot, relative);
if (mode === '--check') assert.equal(fs.readFileSync(filename, 'utf8'), text, 'L8 loader projection drift');
else {
  fs.mkdirSync(path.dirname(filename), {recursive: true});
  fs.writeFileSync(filename, text);
}
console.log(JSON.stringify({kind: 'registry-derived-alg-l08-module-loader-v1', mode,
  input: {path: registryPath, bytes: bytes.length, sha256: hash(bytes)},
  registeredKeys: entries.map(entry => entry.key),
  output: {path: relative, bytes: Buffer.byteLength(text), sha256: hash(text)}}));
