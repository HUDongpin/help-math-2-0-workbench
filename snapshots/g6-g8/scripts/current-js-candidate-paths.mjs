import path from 'node:path';

export const CURRENT_JS_CANDIDATE_VERSION =
  '2026-08-22-page-only-candidates-v1';

export const CURRENT_JS_CANDIDATE_FLASH_ROOT =
  `apps/web/candidate-assets/flash-assets/${CURRENT_JS_CANDIDATE_VERSION}`;

export const CURRENT_JS_CANDIDATE_EVIDENCE_ROOT =
  `candidate-evidence/current-js/${CURRENT_JS_CANDIDATE_VERSION}`;

const PUBLIC_COURSE_PREFIXES = Object.freeze([
  'course-g04-l05-',
  'course-g04-l10-',
  'course-g04-l11-',
]);

const G5_L5_OVERWRITTEN_CANDIDATES = Object.freeze(new Set([
  'course-g05-l05-fq-003',
  'course-g05-l05-ts-007',
  'course-g05-l05-vb-012',
]));

function invariant(condition, message) {
  if (!condition) throw new Error(message);
}

function validateAnimationId(animationId) {
  invariant(
    /^course-g\d{2}-l\d{2}-[a-z]{2}-[a-z0-9-]+$/u.test(animationId),
    `invalid animation ID: ${animationId}`,
  );
  return animationId;
}

function validateSuffix(suffix) {
  const portable = suffix.split(path.sep).join('/');
  invariant(
    portable.length > 0
      && !portable.startsWith('/')
      && !portable.split('/').some((segment) =>
        segment.length === 0 || segment === '.' || segment === '..'
      ),
    `invalid candidate suffix: ${suffix}`,
  );
  return portable;
}

export function currentJsCandidateRuntimePath(animationId, suffix) {
  return `${CURRENT_JS_CANDIDATE_FLASH_ROOT}/courses/` +
    `${validateAnimationId(animationId)}/${validateSuffix(suffix)}`;
}

export function currentJsCandidateEvidencePath(
  animationId,
  suffix,
  evidenceVersion = 'v1',
) {
  invariant(/^v[1-9][0-9]*$/u.test(evidenceVersion),
    `invalid candidate evidence version: ${evidenceVersion}`);
  return `${CURRENT_JS_CANDIDATE_EVIDENCE_ROOT}/courses/` +
    `${validateAnimationId(animationId)}/` +
    `product-candidate-assets-${evidenceVersion}/${validateSuffix(suffix)}`;
}

export function isSeparatedCurrentJsCandidateAnimationId(animationId) {
  return PUBLIC_COURSE_PREFIXES.some((prefix) =>
    animationId.startsWith(prefix)
  ) || G5_L5_OVERWRITTEN_CANDIDATES.has(animationId);
}

/**
 * Translate a historical candidate path under either repository `public/` or
 * `apps/web/public/` into its private candidate/evidence storage path.
 *
 * The historical path remains useful as metadata and as the browser URL. This
 * helper changes only where generated bytes are read and written on disk.
 */
export function separatedCurrentJsCandidateStoragePath(logicalPath) {
  invariant(typeof logicalPath === 'string', 'candidate path must be a string');
  const portable = logicalPath.split(path.sep).join('/');
  const normalized = portable.startsWith('apps/web/')
    ? portable.slice('apps/web/'.length)
    : portable;
  const match = /^public\/flash-assets\/courses\/([^/]+)\/(.+)$/u.exec(
    normalized,
  );
  invariant(match, `not a historical public candidate path: ${logicalPath}`);
  const [, animationId, suffix] = match;
  invariant(
    isSeparatedCurrentJsCandidateAnimationId(animationId),
    `animation is outside the separated candidate scope: ${animationId}`,
  );
  return suffix.endsWith('.json')
    ? currentJsCandidateEvidencePath(animationId, suffix)
    : currentJsCandidateRuntimePath(animationId, suffix);
}
