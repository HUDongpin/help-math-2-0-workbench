import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';

const hash = value => createHash('sha256').update(value).digest('hex');
const input = new URL('../apps/web/components/g678-alg-l06-p025-candidate-player-v1.generated.tsx', import.meta.url);
const output = new URL('../apps/web/components/source-lesson-candidate-player-v1.generated.tsx', import.meta.url);
const source = fs.readFileSync(input, 'utf8');
assert.equal(hash(source), '391de2f1e6dacf2c138d0fe290f6c4dc4f34ac225e4fb2924adc7057d5e75b81');

// Preserve the v1 producer and its exact base projection. This successor adds
// presentation-only copy for a formally registered page; candidateMode still
// governs the private runtime adapter in the generated player.
let text = source.replace(source.split('\n')[0], '// Generated by scripts/build-source-lesson-candidate-player-v1.mjs; do not edit.');
text = text.replaceAll('G678AlgL6P025CandidatePlayer', 'SourceLessonCandidatePlayerV1');
text = text.replaceAll('35 páginas registradas', '${descriptor.schemaVersion === 2 ? descriptor.productBridge.registeredAnimationCount - 1 : 0} páginas registradas');
text = text.replaceAll('35 registered pages', '${descriptor.schemaVersion === 2 ? descriptor.productBridge.registeredAnimationCount - 1 : 0} registered pages');
text = text.replaceAll('35/${descriptor.course.activePageCount}', '${descriptor.schemaVersion === 2 ? descriptor.productBridge.registeredAnimationCount - 1 : 0}/${descriptor.course.activePageCount}');
assert.equal(hash(text), '3754ccdd3e9b4dc5d8132a2f9baa93aa00eff17217ed77b8f00dfe4bae8034f6');

function replaceExact(before, after, count) {
  assert.equal(text.split(before).length - 1, count, `v2 source occurrence: ${before}`);
  text = text.replaceAll(before, after);
}
replaceExact('build-source-lesson-candidate-player-v1.mjs; do not edit.',
  'build-source-lesson-candidate-player-v2.mjs; do not edit.', 1);
replaceExact('  candidateMode,\n  descriptor,',
  "  candidateMode,\n  registeredPagePresentation = 'candidate',\n  descriptor,", 1);
replaceExact('  candidateMode: boolean;\n  descriptor:',
  "  candidateMode: boolean;\n  registeredPagePresentation?: 'candidate' | 'registered';\n  descriptor:", 1);
replaceExact('registeredAnimationCount - 1 : 0',
  "registeredAnimationCount - (registeredPagePresentation === 'registered' ? 0 : 1) : 0", 4);
replaceExact(' y 1 candidato sin registrar',
  "${registeredPagePresentation === 'registered' ? '' : ' y 1 candidato sin registrar'}", 2);
replaceExact(' and 1 unregistered candidate',
  "${registeredPagePresentation === 'registered' ? '' : ' and 1 unregistered candidate'}", 2);

// A source-authored game transition needs both its directions and game pages
// available in one candidate. Keep the existing one-page default for all callers.
replaceExact("  registeredPagePresentation = 'candidate',\n  descriptor,",
  "  registeredPagePresentation = 'candidate',\n  unregisteredCandidateCount = 1,\n  descriptor,", 1);
replaceExact("  registeredPagePresentation?: 'candidate' | 'registered';\n  descriptor:",
  "  registeredPagePresentation?: 'candidate' | 'registered';\n  unregisteredCandidateCount?: number;\n  descriptor:", 1);
replaceExact("registeredPagePresentation === 'registered' ? 0 : 1",
  "registeredPagePresentation === 'registered' ? 0 : unregisteredCandidateCount", 4);
replaceExact("' y 1 candidato sin registrar'",
  "` y ${unregisteredCandidateCount} candidato${unregisteredCandidateCount === 1 ? '' : 's'} sin registrar`", 2);
replaceExact("' and 1 unregistered candidate'",
  "` and ${unregisteredCandidateCount} unregistered candidate${unregisteredCandidateCount === 1 ? '' : 's'}`", 2);

// V3 adds the optional source-authored exit callback to the existing adapter.
replaceExact('build-source-lesson-candidate-player-v2.mjs; do not edit.',
  'build-source-lesson-candidate-player-v3.mjs; do not edit.', 1);
replaceExact('        connectRuntimeControls={connectRuntimeControls}',
  '        connectRuntimeControls={connectRuntimeControls}\n        onSourceExit={exitToLearningHome}', 1);

assert(['--write', '--check'].includes(process.argv[2]));
const current = fs.readFileSync(output, 'utf8');
if (process.argv[2] === '--check') assert.equal(current, text);
else if (['58502eb2c2a8f8c48ee7c6b967cf5c98a98169170a1466abc61b85c18036164b','3754ccdd3e9b4dc5d8132a2f9baa93aa00eff17217ed77b8f00dfe4bae8034f6','5119dd9d88dc5de090a0dc1cb3ed5e7b8fa905bcdc3b1cafb9940ed8b764db64'].includes(hash(current)))
  fs.writeFileSync(output, text);
else assert.equal(current, text, 'v2 output was neither the pinned v1 preimage nor this exact successor');
console.log('My Lesson shared registered-page presentation: source-pinned, candidate default retained');
