#!/usr/bin/env node
// Bounded private glossary policy successor; the pinned v4 player remains frozen.
import assert from 'node:assert/strict';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {ROOT, readBound, pin, encode} from './lib/g678-terminal-source-generator-v5.mjs';

export const BASE = Object.freeze({
  path: 'apps/web/components/g678-multi-page-lesson-player-v4.generated.tsx',
  bytes: 53823,
  sha256: '98f6bc63ba01cd402484099861c5ab0122c6a4ff0171c6d89ba314fe12434544',
});
export const OUTPUT = 'apps/web/components/g678-multi-page-lesson-player-v5.generated.tsx';
export const MANIFEST = 'catalog/product-bridge-calibrations/g678-multi-page-lesson-player-v5.json';

export async function buildMultiPagePlayerV5({check = false} = {}) {
  let next = (await readBound(BASE.path, BASE)).bytes.toString();
  const edits = [
    ['// Generated by scripts/build-g678-multi-page-lesson-player-v4.mjs; do not edit.',
      '// Generated by scripts/build-g678-multi-page-lesson-player-v5.mjs; do not edit.'],
    ["'use client';", "'use client';\nimport {resolvePrivatePlaybackPaused} from '@/lib/g678-private-playback-decision-v1';"],
    ['  const setPlaybackPaused=(value:boolean)=>{currentAdapterControls()?.setPaused(value);setPaused(value);};',
      '  const setPlaybackPaused=(value:boolean)=>{const acknowledgement=currentAdapterControls()?.setPaused(value);setPaused(resolvePrivatePlaybackPaused(value, acknowledgement));};'],
    ['    setSeekRequest(null);\n    setPaused(false);',
      '    setSeekRequest(null);\n    setPlaybackPaused(false);'],
  ];
  for (const [before, after] of edits) {
    assert.equal(next.split(before).length, 2, 'exact pinned v4 edit');
    next = next.replace(before, after);
  }
  const inputs = [BASE, ...await Promise.all([
    'catalog/product-bridge-calibrations/g678-multi-page-lesson-player-v4.json',
    'scripts/build-g678-multi-page-lesson-player-v5.mjs',
    'apps/web/lib/lesson-runtime-adapter.ts',
    'apps/web/lib/descriptor-driven-glossary-pause.ts',
    'apps/web/lib/g678-private-glossary-pause-v1.ts',
    'apps/web/lib/g678-private-playback-decision-v1.ts',
    'apps/web/lib/g678-private-runtime-adapters-v1.ts',
  ].map(async file => (await readBound(file)).binding))];
  const manifest = {
    schemaVersion: 1,
    scope: 'Private playback acknowledgement; v4 and ordinary pages remain unchanged',
    inputs,
    output: pin(OUTPUT, next),
    edits: edits.map(([before, after]) => ({before, after})),
    sourceBaseChanged: false,
    originalRuntimeAccepted: false,
    scaleOutAuthorized: false,
  };
  for (const [file, bytes] of [[OUTPUT, next], [MANIFEST, encode(manifest)]]) {
    const full = path.join(ROOT, file);
    const existing = await readFile(full).catch(error => {
      if (error.code === 'ENOENT') return null;
      throw error;
    });
    if (check || existing) assert(existing && existing.equals(Buffer.from(bytes)), `derived host drift: ${file}`);
    if (!check && !existing) {
      await mkdir(path.dirname(full), {recursive: true});
      await writeFile(full, bytes, {flag: 'wx'});
    }
  }
  return {check, output: manifest.output, sourceBaseChanged: false};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  assert(process.argv.length === 2 || process.argv.length === 3 && process.argv[2] === '--check');
  console.log(encode(await buildMultiPagePlayerV5({check: process.argv[2] === '--check'})));
}
