#!/usr/bin/env node
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {mkdir,readFile,writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {compile,forbidden} from './g678-nms-l01-p044-build-source-canvas.mjs';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const PREVIOUS='packages/demos/src/generated/g678-nms-l01-p044-source-canvas-v1.ts';
const GENERATED='packages/demos/src/generated/g678-nms-l01-p044-prepared-source-canvas-v2.ts';
const RUN='work/g678-shared-page-factory/g678-nms-l01-p044-prepared-source-canvas-v2';
const hash=b=>createHash('sha256').update(b).digest('hex');
async function binding(p){const bytes=await readFile(path.resolve(ROOT,p));return{path:p,bytes:bytes.length,sha256:hash(bytes)};}
export function extractPreparedImages(source){
  const assets={};
  const imagePattern=/var (imageObj\d+) = document\.createElement\("img"\);\n\1\.src=("data:image\/[^"]+");/g;
  let transformed=source.replace(imagePattern,(_,name,literal)=>{assert.equal(assets[name],undefined);assets[name]=JSON.parse(literal);return `var ${name}=preparedImages[${JSON.stringify(name)}];`;});
  assert.equal(Object.keys(assets).length,10,'Exactly ten source bitmaps');
  const rootPattern=/const rootImage=document\.createElement\("img"\);rootImage\.src=("data:image\/svg\+xml;base64,[^"]+");/g;
  let roots=0;transformed=transformed.replace(rootPattern,(_,literal)=>{roots++;assets.rootImage=JSON.parse(literal);return 'const rootImage=preparedImages.rootImage;';});
  assert.equal(roots,1);assert.ok(!transformed.includes('createElement("img")'));
  const header='export function createP044SourceCanvasAdapter(targetCanvas) {';
  assert.equal(transformed.split(header).length-1,1);
  transformed=transformed.replace(header,'export function createP044PreparedSourceCanvasAdapter(targetCanvas,preparedImages) {');
  const marker='"use strict";\n';assert.equal(transformed.split(marker).length-1,1);
  transformed=transformed.replace(marker,marker+`if(!preparedImages||Object.keys(preparedImages).sort().join('|')!==Object.keys(P044_SOURCE_IMAGE_URIS).sort().join('|'))throw Error('Exact p044 prepared image set required');
for(const [name,uri]of Object.entries(P044_SOURCE_IMAGE_URIS)){const image=preparedImages[name];if(!image||image.src!==uri||!image.complete||image.naturalWidth<1||image.naturalHeight<1)throw Error('Unready or foreign p044 image:'+name);}
`);
  const code=`// @ts-nocheck -- generated exact source drawings; no automatic resource loading.\n// Generated by build-g678-nms-l01-p044-prepared-canvas.mjs; do not edit.\nexport const P044_SOURCE_IMAGE_URIS=Object.freeze(${JSON.stringify(assets)});\n${transformed}`;
  forbidden(code);return{code,assets};
}
export async function buildPrepared(){
  const previous=await binding(PREVIOUS);assert.equal(previous.sha256,'a2c12a7265bdc6f7df923abd966af471d05b36987b1deaa5baf521b8128bc80e');
  const priorRunPath='work/g678-shared-page-factory/g678-nms-l01-p044-source-canvas-v1/run.json';
  const priorRun=JSON.parse(await readFile(priorRunPath,'utf8'));for(const expected of priorRun.inputs)assert.deepEqual(await binding(expected.path),expected);
  const compiled=await compile();
  assert.equal(hash('// @ts-nocheck -- generated source glyph/morph frontend; typed adapter contract is root-owned.\n'+compiled.code),previous.sha256,'Recompiled V1 drawings must match retained V1 exactly');
  const {code,assets}=extractPreparedImages(compiled.code);
  const inputs=await Promise.all([PREVIOUS,priorRunPath,'scripts/build-g678-nms-l01-p044-prepared-canvas.mjs',
    'scripts/build-g678-nms-l01-p044-prepared-canvas.test.mjs',...priorRun.inputs.map(i=>i.path)].map(binding));
  const manifest={artifactType:'exact-p044-prepared-canvas-resource-successor',inputs,
    output:{path:GENERATED,bytes:Buffer.byteLength(code),sha256:hash(code)},
    images:Object.entries(assets).map(([id,uri])=>({id,mime:uri.slice(5,uri.indexOf(';')),dataUriSha256:hash(uri),decodedContainerBytes:Buffer.from(uri.split(',')[1],'base64').length})),
    transformation:'Move only eleven image resource declarations into an exact predecoded input set. Source glyph/shape/morph/display-list functions and sourceDraw remain unchanged.',
    readiness:'Caller must await actual image decode before module admission; adapter construction rejects incomplete or foreign resources.',
    gates:{currentJavaScriptRegistered:false,productCalibrationPassed:false,originalRuntimeAccepted:false,audioAccepted:false,humanAccepted:false,ownerAccepted:false,strictComplete:false,released:false,published:false}};
  return{code,manifest};
}
async function main(){assert.ok(['--write','--check'].includes(process.argv[2]));assert.equal(process.argv.length,3);const{code,manifest}=await buildPrepared();
  const files=[[GENERATED,code],[`${RUN}/run.json`,JSON.stringify(manifest,null,2)+'\n']];
  if(process.argv[2]==='--write')await mkdir(path.join(ROOT,RUN));
  for(const[p,b]of files)if(process.argv[2]==='--write')await writeFile(path.join(ROOT,p),b,{flag:'wx',mode:0o444});else assert.equal(await readFile(path.join(ROOT,p),'utf8'),b,p);
  console.log(JSON.stringify({mode:process.argv[2],filesWritten:process.argv[2]==='--write'?2:0,files:files.map(([path,b])=>({path,bytes:Buffer.byteLength(b),sha256:hash(b)}))},null,2));}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))await main();
