import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import fs from 'node:fs';

const input=new URL('../apps/web/components/g678-alg-l06-p004-formal-player-v1.generated.tsx',import.meta.url);
let source=fs.readFileSync(input,'utf8');
assert.equal(createHash('sha256').update(source).digest('hex'),
  'fd7e9bcb4f4fa85da7b18825c048a3593eb4ced97de96a9a8dc0cbc9217a3a53');
for(const [from,to] of [
  ['G678AlgL6P004FormalPlayer','G678AlgL6P015CandidatePlayer'],
  ['${registeredPages.length}/${descriptor.pages.length} páginas current-JS;',
    '25 páginas registradas y 1 candidato sin registrar de ${descriptor.pages.length};'],
  ['${registeredPages.length}/${descriptor.pages.length} current-JS pages;',
    '25 registered pages and 1 unregistered candidate of ${descriptor.pages.length};'],
  ['${registeredPages.length}/${descriptor.course.activePageCount} páginas registradas en el host moderno My Lesson',
    '25/${descriptor.course.activePageCount} páginas registradas y 1 candidato sin registrar en My Lesson'],
  ['${registeredPages.length}/${descriptor.course.activePageCount} pages registered in the modern My Lesson host',
    '25/${descriptor.course.activePageCount} registered pages and 1 unregistered candidate in My Lesson'],
]){
  assert.equal(source.split(from).length,2);
  source=source.replace(from,to);
}
source=source.replace(source.split('\n')[0],
  '// Generated by scripts/generate-alg-l06-p015-candidate-player-v1.mjs; do not edit.');

const target=new URL('../apps/web/components/g678-alg-l06-p015-candidate-player-v1.generated.tsx',import.meta.url);
assert(['--write','--check'].includes(process.argv[2]));
if(process.argv[2]==='--write')fs.writeFileSync(target,source);
else assert.equal(fs.readFileSync(target,'utf8'),source);
console.log('P015 candidate player verified; 25 registered + 1 unregistered candidate');
