#!/usr/bin/env node

import {createHash} from 'node:crypto';
import {readFile, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const inputPath = path.join(projectRoot, 'migrations/shared-alg001-l06-p001/audit/title-timeline-v1.json');
const inputSha256 = 'feb68badd3bb5c8e8fd7ff1857789d7253a3fce0e10124a22b47ab2bdbe6b280';
const outputPath = path.join(projectRoot, 'packages/demos/src/alg-l06-p001-title-data-v1.ts');

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

export async function renderTitleData() {
  const input = await readFile(inputPath);
  if (sha256(input) !== inputSha256) throw new Error('P001 source title IR SHA-256 drift');
  const ir = JSON.parse(input.toString('utf8'));
  if (
    ir.animationId !== 'shared-alg001-l06-p001' || ir.titleFrameDomain !== 'sprite-142' ||
    ir.rootTitlePlacement?.frame !== 6 || ir.titleFrameCount !== 134 ||
    ir.frames?.length !== 134 || ir.textObjects?.length !== 2 ||
    ir.textObjects.some((row) => row.text !== 'Understanding Functions: Introduction')
  ) throw new Error('P001 source title IR contract drift');
  const rows = ir.frames.map((row, index) => {
    if (row.frame !== index + 1 || row.layers?.length !== 2) {
      throw new Error(`P001 title frame ${index + 1} identity drift`);
    }
    const tuples = row.layers.map((layer, layerIndex) => {
      if (layer.depth !== layerIndex + 1 || layer.characterId !== 140 + layerIndex) {
        throw new Error(`P001 title frame ${index + 1} layer identity drift`);
      }
      return [layer.scaleX, layer.scaleY, layer.transXTwips,
        layer.transYTwips, layer.alpha256];
    });
    return `  [${tuples.map((tuple) => `[${tuple.join(', ')}]`).join(', ')}],`;
  });
  return `// Generated by scripts/build-g678-alg-l06-p001-title-data.mjs; do not edit.\n` +
    `// Source IR SHA-256: ${inputSha256}\n` +
    `export type TitleLayerTuple = readonly [scaleX: number, scaleY: number, transXTwips: number, transYTwips: number, alpha256: number];\n` +
    `export const SOURCE_TITLE_TEXT = ${JSON.stringify(ir.textObjects[0].text)};\n` +
    `export const SOURCE_TITLE_ROOT_ENTRY = {frame: 6, xTwips: 8248, yTwips: 5666} as const;\n` +
    `export const SOURCE_TITLE_FRAMES: ReadonlyArray<readonly [TitleLayerTuple, TitleLayerTuple]> = [\n` +
    `${rows.join('\n')}\n];\n`;
}

export async function buildTitleData({check = false, output = outputPath} = {}) {
  const expected = Buffer.from(await renderTitleData());
  if (check) {
    const current = await readFile(output);
    if (!current.equals(expected)) throw new Error('P001 generated title data drift');
  } else {
    await writeFile(output, expected, {flag: 'wx'});
  }
  return {mode: check ? 'check' : 'write', output: path.relative(projectRoot, output),
    sha256: sha256(expected), frameCount: 134};
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const mode = process.argv[2];
  if (!['--write', '--check'].includes(mode) || process.argv.length !== 3) {
    console.error('Usage: node scripts/build-g678-alg-l06-p001-title-data.mjs --write|--check');
    process.exitCode = 2;
  } else {
    buildTitleData({check: mode === '--check'})
      .then((result) => console.log(JSON.stringify(result)))
      .catch((error) => { console.error(error.message); process.exitCode = 1; });
  }
}
