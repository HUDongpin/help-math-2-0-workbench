import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile,writeFile,mkdir,access} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {spawnSync} from 'node:child_process';

const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const AUDIT='work/g678-shared-page-factory/frozen16-glossary-audit-v1/audit.json';
const OUTPUT='work/g678-shared-page-factory/frozen16-glossary-candidates-v1';
const WRAPPER='packages/demos/src/frozen-calibration-glossary-candidate.tsx';
const json=x=>JSON.stringify(x,null,2)+'\n';
const digest=b=>createHash('sha256').update(b).digest('hex');
const binding=(p,b)=>({path:p,bytes:Buffer.byteLength(b),sha256:digest(b)});
async function main(){
  assert(process.argv.length===2||process.argv.length===3&&process.argv[2]==='--check');const check=process.argv[2]==='--check';
  const verified=spawnSync('python3',['scripts/audit-g678-frozen16-glossary.py','--check'],{cwd:ROOT,encoding:'utf8'});assert.equal(verified.status,0,verified.stderr);
  const auditBytes=await readFile(path.join(ROOT,AUDIT)),audit=JSON.parse(auditBytes);
  assert.deepEqual(audit.summary,{pages:8,buttonDefinitions:41,distinctTerms:33});
  const outputs=new Map(),entries=[];
  for(const row of audit.records){
    const stem=`frozen16-glossary-${row.animationId}`,constant=row.animationId.replaceAll('-','_').toUpperCase();
    const controls=row.buttons.map(({sourceCharacterId,sourceKeyAttribute,entryId,labels,ranges})=>({sourceCharacterId,sourceKeyAttribute,entryId,labels,ranges}));
    const timeline=`// Generated by build-g678-frozen16-glossary-candidates.mjs; do not edit.\nimport {${constant}_CONFIG as base} from './${row.animationId}';\nexport const CONFIG=Object.freeze({...base,showEngineeringDisclosure:false});\nexport const CONTROLS=${JSON.stringify(controls,null,2)} as const;\n`;
    const module=`// Generated by build-g678-frozen16-glossary-candidates.mjs; do not edit.\n"use client";\nimport {createFrozenCalibrationGlossaryCandidate} from '../frozen-calibration-glossary-candidate';\nimport {CONFIG,CONTROLS} from '../timelines/${stem}';\nconst candidate=createFrozenCalibrationGlossaryCandidate(CONFIG,CONTROLS);\nexport const glossaryControls=candidate.controls;\nexport default candidate.module;\n`;
    const t=`packages/demos/src/timelines/${stem}.ts`,m=`packages/demos/src/modules/${stem}.tsx`;
    outputs.set(t,timeline);outputs.set(m,module);
    const previousTimeline=`packages/demos/src/timelines/${row.animationId}.ts`;
    const previous=await readFile(path.join(ROOT,previousTimeline));
    entries.push({key:row.animationId,module:`./modules/${stem}`,complexityLane:'interactive-understood',maturity:'private-current-js',
      source:row.source,controls,glossaryEntries:row.buttons.map(b=>({id:b.entryId,sourceKeyAttribute:b.sourceKeyAttribute,labels:b.labels,definitions:b.definitions,
        source:{en:{assetId:'G678L1KTE01.xml',...b.dictionary.en},es:{assetId:'G678L1KTS01.xml',...b.dictionary.es}}})),
      artifacts:{module:binding(m,module),timeline:binding(t,timeline),runtime:{path:row.runtime.canvasRenderer.path,bytes:row.runtime.canvasRenderer.bytes,sha256:row.runtime.canvasRenderer.sha256}},
      predecessorTimeline:binding(previousTimeline,previous),runtime:row.runtime,
      presentation:{pageInteractionCompanionTargetIdSuffix:'frozen16-glossary-controls'},
      currentJavaScriptRegistered:false,productCalibrationPassed:false});
  }
  const manifest={schemaVersion:1,artifactType:'g678-frozen16-glossary-candidates-v1',entries,
    inputs:[binding(AUDIT,auditBytes),binding(WRAPPER,await readFile(path.join(ROOT,WRAPPER))),
      binding('scripts/build-g678-frozen16-glossary-candidates.mjs',await readFile(fileURLToPath(import.meta.url)))],
    outputs:[...outputs].map(([p,b])=>binding(p,b)),
    acceptanceEffects:{registered:false,productCalibrationPassed:false,scaleOutAuthorized:false,originalRuntimeAccepted:false,audioAccepted:false,humanAccepted:false,ownerAccepted:false,strictComplete:false,published:false}};
  outputs.set(`${OUTPUT}/manifest.json`,json(manifest));
  if(check){for(const[p,b]of outputs)assert.equal((await readFile(path.join(ROOT,p))).toString(),b,p);}
  else{
    for(const p of outputs.keys())await assert.rejects(access(path.join(ROOT,p)),{code:'ENOENT'});
    await mkdir(path.join(ROOT,OUTPUT));
    for(const[p,b]of outputs)await writeFile(path.join(ROOT,p),b,{flag:'wx'});
  }
  console.log(json({pages:entries.length,generatedFiles:outputs.size,check,registrationChanged:false}));
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url))main().catch(e=>{console.error(e);process.exitCode=1;});
