function canonicalPath(root, file) {
  assert.ok(typeof file === 'string' && !path.isAbsolute(file) && file.split('/').every(s => s && s !== '.' && s !== '..'), 'Non-canonical workspace path');
  const target = path.resolve(root, file); assert.ok(target.startsWith(root + path.sep)); return target;
}
async function readCanonical(absolute, bindingPath, expected) {
  const [canonical, before] = await Promise.all([realpath(absolute), lstat(absolute, {bigint: true})]);
  assert.ok(canonical === absolute && before.isFile() && !before.isSymbolicLink() && before.nlink === 1n);
  const buffer = await readFile(absolute), after = await lstat(absolute, {bigint: true});
  for (const key of ['ino', 'dev', 'size', 'mtimeNs', 'mode', 'nlink']) assert.equal(before[key], after[key], 'Input read drift');
  const binding = descriptor(bindingPath, buffer); if (expected) assert.deepEqual(binding, expected, `Input drift: ${bindingPath}`);
  return {binding, buffer, value: bindingPath.endsWith('.json') ? JSON.parse(buffer) : null};
}
const bound = (file, expected) => readCanonical(canonicalPath(ROOT, file), file, expected);
async function dependency(file, expected) {
  const resolved = await realpath(path.resolve(ROOT, file)), dependencyRoot = await realpath(path.join(ROOT, 'node_modules'));
  return resolved.startsWith(dependencyRoot + path.sep)
    ? readCanonical(resolved, resolved, expected) : bound(file, expected);
}

