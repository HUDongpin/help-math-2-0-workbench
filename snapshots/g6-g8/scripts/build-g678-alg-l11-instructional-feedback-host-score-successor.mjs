export function composeFeedbackHostScoreFragment({predecessor, p044Predecessor, replacement, p034CompilerRun}) {
  assert.deepEqual(descriptor(PREDECESSOR_FRAGMENT.path, json(predecessor)), PREDECESSOR_FRAGMENT, 'Exact original23 authority required');
  assert.deepEqual(descriptor(P044_FRAGMENT.path, json(p044Predecessor)), P044_FRAGMENT, 'Exact frozen p044 authority required');
  assert.equal(predecessor.artifactType, 'g678-alg-l11-instructional-successor-current-js-fragment-v1');
  assert.equal(p044Predecessor.artifactType, 'g678-alg-l11-instructional-host-score-successor-fragment-v1');
  assert.deepEqual(predecessor.compilerRun, PREDECESSOR_RUN); assert.deepEqual(p044Predecessor.compilerRun, PREDECESSOR_RUN);
  assert.deepEqual(p044Predecessor.p044CompilerRun, P044_RUN);
  assert.deepEqual(p044Predecessor.predecessorFragment, PREDECESSOR_FRAGMENT);
  assert.deepEqual(p044Predecessor.sourceP044Manifest, SOURCE_P044_MANIFEST);
  for (const root of [predecessor, p044Predecessor]) {
    assert.equal(root.schemaVersion, 1); assert.equal(root.deploymentScope, 'local-only');
    assert.deepEqual(root.entries.map(entry => entry.key), SOURCE_IDS);
    for (const field of ['exactPlacementCount', 'generatedPlacementCount', 'currentJavaScriptImplementedPlacementCount', 'domRendererImplementedCount']) assert.equal(root[field], 23);
    for (const field of ['registryEntriesWritten', 'registrationCandidatePlacementCount', 'currentJavaScriptRegisteredCount', 'wholeLessonEngineeringPreviewCount']) assert.equal(root[field], 0);
    for (const field of ['productCalibrationPassed', 'browserProductCalibrationPassed', 'scaleOutAuthorized', 'acceptancePassed', 'releaseAuthorized', 'published']) assert.equal(root[field], false);
    assert.ok(Object.keys(root.acceptanceEffects).length > 0 && Object.values(root.acceptanceEffects).every(value => value === false));
  }
  assert.deepEqual(p044Predecessor.entries.filter(e => e.key !== P044_ID), predecessor.entries.filter(e => e.key !== P044_ID));
  const previous = predecessor.entries.find(e => e.key === ID), p044 = p044Predecessor.entries.find(e => e.key === P044_ID);
  assert.deepEqual(without(replacement, ['module', 'moduleFile', 'timeline', 'memberManifest', 'runtimeContract']),
    without(previous, ['module', 'moduleFile', 'timeline', 'memberManifest', 'runtimeContract']));
  assert.deepEqual(replacement.runtimeContract, {...previous.runtimeContract, lessonHostCapabilities: ['practice-feedback']});
  assert.equal(replacement.module, './modules/' + path.basename(OUTPUT_PATHS.module, '.tsx'));
  for (const [key, file] of [['moduleFile', OUTPUT_PATHS.module], ['timeline', OUTPUT_PATHS.timeline], ['memberManifest', OUTPUT_PATHS.member]]) {
    assert.equal(replacement[key].path, file);
    assert.ok(Number.isSafeInteger(replacement[key].bytes) && replacement[key].bytes > 0 && /^[a-f0-9]{64}$/.test(replacement[key].sha256));
  }
  assert.equal(p034CompilerRun.path, OUTPUT_PATHS.run);
  assert.ok(Number.isSafeInteger(p034CompilerRun.bytes) && p034CompilerRun.bytes > 0 && /^[a-f0-9]{64}$/.test(p034CompilerRun.sha256));
  const entries = predecessor.entries.map(entry => structuredClone(entry.key === ID ? replacement : entry.key === P044_ID ? p044 : entry));
  assert.deepEqual(entries.filter(e => e.key !== ID && e.key !== P044_ID), predecessor.entries.filter(e => e.key !== ID && e.key !== P044_ID));
  assert.deepEqual(entries.find(e => e.key === P044_ID), p044);
  return {...structuredClone(predecessor), artifactType: 'g678-alg-l11-instructional-feedback-host-score-successor-fragment-v1',
    runId: 'g678-alg-l11-instructional-feedback-host-score-successor-v1', compilerRun: PREDECESSOR_RUN,
    p034CompilerRun, p044CompilerRun: P044_RUN, predecessorFragment: PREDECESSOR_FRAGMENT,
    p044PredecessorFragment: P044_FRAGMENT, sourceP034Manifest: SOURCE_P034_MANIFEST, sourceP044Manifest: SOURCE_P044_MANIFEST,
    changedPlacementCount: 2, newlyGeneratedPlacementCount: 1, reusedSuccessorPlacementCount: 1,
    inheritedPlacementCount: 21, newlyGeneratedVisualPayloadCount: 0, entries, registryEntriesWritten: 0};
}

async function ensureDirectory(root, relative) {
  canonicalPath(root, relative); let current = root;
  for (const segment of relative.split('/')) {
    current = path.join(current, segment);
    try {await mkdir(current);} catch (error) {if (error.code !== 'EEXIST') throw error;}
    const stat = await lstat(current);
    assert.ok(stat.isDirectory() && !stat.isSymbolicLink() && await realpath(current) === current, 'Output directory must not traverse symlinks');
  }
}
export async function publishFeedbackOutputs({root = ROOT, outputs, check = false}) {
  assert.deepEqual([...outputs.keys()].sort(), Object.values(OUTPUT_PATHS).sort(), 'Only six exact new output paths allowed');
  assert.equal([...outputs.keys()].at(-1), FRAGMENT, 'Composite authority must be published last');
  if (check) {
    for (const [file, content] of outputs) {
      const absolute = canonicalPath(root, file), stat = await lstat(absolute);
      assert.ok(stat.isFile() && !stat.isSymbolicLink() && stat.nlink === 1 && await realpath(absolute) === absolute);
      assert.ok((await readFile(absolute)).equals(Buffer.from(content)), `Generated output drift: ${file}`);
    }
  } else {
    for (const file of outputs.keys()) await assert.rejects(lstat(canonicalPath(root, file)), {code: 'ENOENT'}, 'Exclusive output exists');
    for (const [file, content] of outputs) {
      await ensureDirectory(root, path.dirname(file)); await writeFile(canonicalPath(root, file), content, {flag: 'wx', mode: 0o444});
    }
  }
}

