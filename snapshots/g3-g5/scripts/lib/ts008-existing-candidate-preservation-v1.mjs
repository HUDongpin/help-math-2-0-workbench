import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';

export const TS008_ASSET_PATH = 'courses/course-g03-l01-ts-008/canvas-renderer.js';
export const TS008_BASE_BYTES = 9026835;
export const TS008_BASE_SHA256 = '77373bbb8f8511fd657048341507eea5bac314ff112d3ca35f339eefc1a84fac';
export const TS008_EFFECTIVE_BYTES = 9027191;
export const TS008_EFFECTIVE_SHA256 = '863191baf3afc666cdd0ad5db837fe79fdc8892e502137ed75bde9e95f15f090';
export const TS008_SWF_SHA256 = '9749ae5f4d533379aa58531e541ffd5da1624bc8fcea38660d54d0f5d3ddc29b';
export const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
const OLD_HEADER = '/* Generated by scripts/build-safe-ffdec-canvas-adapter.mjs. */';
const NEW_HEADER = '/* Generated by scripts/build-g3-l05-page-only-candidate-bundle.mjs. */';
const METADATA_PREFIX = 'var METADATA = deepFreeze(';
const METADATA_END = ');\nvar readyPromise = null;';
const DRAWING_BYTES = 9019443;
const DRAWING_SHA256 = '8ec3f07ce84ef8a4c07b5b9bbad8b98dc54f73818756156f64d47955baaf51e5';

function replaceOnce(source, before, after) {
  const index = source.indexOf(before);
  assert(index >= 0 && source.indexOf(before, index + before.length) === -1,
    'Preserved TS008 envelope marker changed');
  return source.slice(0, index) + after + source.slice(index + before.length);
}

// Preserve the already-existing V12 candidate envelope. This never changes the
// drawing closure, extracts no new behavior, and accepts only the frozen old pack.
// Source helpers: build-safe-ffdec-canvas-adapter metadataForRuntime and
// build-g3-l05-page-only-candidate-bundle adapterSpec/stageMatrix/applyStageMatrix.
export function generateTs008PreservedRuntime(baseBytes) {
  assert(Buffer.isBuffer(baseBytes) || baseBytes instanceof Uint8Array,
    'TS008 base must be bytes');
  const input = Buffer.from(baseBytes);
  assert.equal(input.length, TS008_BASE_BYTES, 'TS008 base size changed');
  assert.equal(digest(input), TS008_BASE_SHA256, 'TS008 base hash changed');
  const source = input.toString('utf8');
  assert(Buffer.from(source).equals(input), 'TS008 base UTF-8 changed');
  assert(source.startsWith(OLD_HEADER + '\n'));
  const start = source.indexOf(METADATA_PREFIX);
  const end = source.indexOf(METADATA_END, start);
  assert(start > 0 && end > start && source.indexOf(METADATA_PREFIX, start + 1) === -1);
  const drawing = source.slice(OLD_HEADER.length + 1, start);
  assert.equal(Buffer.byteLength(drawing), DRAWING_BYTES);
  assert.equal(digest(drawing), DRAWING_SHA256);
  const rawMetadata = source.slice(start + METADATA_PREFIX.length, end);
  const metadata = JSON.parse(rawMetadata);
  assert.equal(metadata.animationId, 'course-g03-l01-ts-008');
  assert.equal(metadata.sourceSwfSha256, TS008_SWF_SHA256);
  assert.equal(metadata.deterministicContentTimeline.timelineId, 'sprite-348');
  assert.equal(metadata.deterministicContentTimeline.frameCount, 747);
  assert.equal(metadata.sourceRootTimeline.beginFrame, 6);
  assert.deepEqual(metadata.sourceRootTimeline.placementPixels, {x: 412.35, y: 282.9});
  const placement = {a: 1, b: 0, c: 0, d: 1, tx: 412.35, ty: 282.9};
  // These internal translation values are pinned by the preserved TS008 spec.
  const matrix = {a: 1, b: 0, c: 0, d: 1,
    e: placement.tx - 1246.6, f: placement.ty - 650};
  metadata.classification = 'lesson-g03-l01-place-value-page-only-candidate-page-only-source-static-current-javascript-candidate';
  metadata.generatorInput.ffdec = 'JPEXS Free Flash Decompiler 26.2.1';
  metadata.sourceRootTimeline.placementMatrix = placement;
  metadata.deterministicContentTimeline.playbackMode = 'once';
  metadata.stageRenderOffset = {x: matrix.e, y: matrix.f};
  metadata.scenarios = ['source-static-frame'];
  metadata.seedMapping = 'no-randomness-injected-into-source-static-frame-rendering';
  metadata.stageRenderMatrix = matrix;
  metadata.frameGateDisposition = 'private source-static frames; natural AVM1 behavior is not claimed';
  let output = replaceOnce(source, OLD_HEADER, NEW_HEADER);
  output = replaceOnce(output, METADATA_PREFIX + rawMetadata + ');',
    METADATA_PREFIX + JSON.stringify(metadata, null, 2) + ');');
  output = replaceOnce(output, 'var allowedScenarios = ["source-drawing-default"];',
    'var allowedScenarios = ["source-static-frame"];');
  output = replaceOnce(output,
    'var scenario = request.scenario === undefined ? "source-drawing-default" : request.scenario;',
    'var scenario = request.scenario === undefined ? "source-static-frame" : request.scenario;');
  output = replaceOnce(output, 'ctx.transform(1, 0, 0, 1, -834.25, -367.1);',
    'ctx.transform(1, 0, 0, 1, ' + matrix.e + ', ' + matrix.f + ');');
  assert.equal(output.slice(NEW_HEADER.length + 1, output.indexOf(METADATA_PREFIX)), drawing);
  const bytes = Buffer.from(output);
  assert.equal(bytes.length, TS008_EFFECTIVE_BYTES, 'Preserved TS008 effective size changed');
  assert.equal(digest(bytes), TS008_EFFECTIVE_SHA256, 'Preserved TS008 effective hash changed');
  return bytes;
}
